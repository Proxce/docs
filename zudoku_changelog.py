#!/usr/bin/env python3
"""
zudoku_changelog.py - build the Changelog tab from the Zudoku release notes.

The Zudoku project (O:/zudoku-1 by default) keeps one Markdown file per product
per month under pages/changelog/<product>/<month><year>.mdx. This script turns
each product into one page of Mintlify <Update> entries, newest first, laid out
the way Okta's release notes are: a summary table of the release, then one short
section per change with a badge and a link to its guide.

    python zudoku_changelog.py                       # write changelog/*.mdx
    python zudoku_changelog.py --zudoku D:/zudoku-1  # another checkout
    python zudoku_changelog.py --dry-run             # report only

The pages it writes carry GENERATED_MARK and are rewritten on every run: edit
the Zudoku source (or this script), never changelog/*.mdx. Run build_nav.py
afterwards only if the product list changed - the pages are pinned in
navigation.json.

What it does to the source:

- "# RELEASE UPDATE - <MONTH> <YEAR>" starts a release; a file may hold two
  (the mid-month releases). "latest version (x)" becomes the release version.
- The product banner and blurb repeated at the top of every month are shown
  once, at the top of the page. "## What's New?" is dropped (every entry is).
- "## <Product area>" inside a release becomes a small section label; each
  "### <change>" becomes a change with a badge, listed in the summary table.
- Badges come from the wording Zudoku already uses:
      "now supports" / "can now" / anything else   -> New
      "An enhancement has been made" / "improved"  -> Improved
      "navigation" / "instructions" updates        -> Updated
      "bug fix"                                    -> Fixed
- Links to oloid.help/en/articles/<id> point at the page migrated from <id>
  when intercom_manifest.json has a published one, and keep their URL
  otherwise. "?utm_source=..." is stripped.

Not migrated, on purpose: pages/changelog/upcoming/* (empty or "coming soon"),
releasenotes.mdx (placeholder API notes) and webkeylog.mdx (not in Zudoku's
navigation, superseded by webkey/*).
"""

import argparse
import datetime
import glob
import io
import json
import os
import re
import sys

GENERATED_MARK = "Generated by zudoku_changelog.py"
OUT_DIR = "changelog"
MANIFEST = "intercom_manifest.json"

# Zudoku directory -> page. Order is the sidebar and landing-page order.
PRODUCTS = [
    {"dir": "admin-portal", "slug": "admin-portal", "title": "Tenant Admin Portal",
     "short": "Admin Portal", "icon": "gauge", "family": "Web portals"},
    {"dir": "user-portal", "slug": "user-portal", "title": "User Portal",
     "short": "User Portal", "icon": "circle-user", "family": "Web portals"},
    {"dir": "windows", "slug": "windows", "title": "Windows Login",
     "short": "Windows", "icon": "windows", "icon_type": "brands", "family": "Apps"},
    {"dir": "android", "slug": "android", "title": "Android",
     "short": "Android", "icon": "android", "icon_type": "brands", "family": "Apps"},
    {"dir": "ios", "slug": "ios", "title": "iOS (Oloid Connect & Verify)",
     "short": "iOS", "icon": "apple", "icon_type": "brands", "family": "Apps"},
    {"dir": "webkey", "slug": "webkey", "title": "WebKey",
     "short": "WebKey", "icon": "key", "family": "Apps"},
    {"dir": "oloid-vault", "slug": "oloid-vault", "title": "Oloid Vault",
     "short": "Oloid Vault", "icon": "vault", "family": "Apps"},
]

MONTHS = ["january", "february", "march", "april", "may", "june", "july",
          "august", "september", "october", "november", "december"]

BADGES = {
    "New": "cl-new",
    "Improved": "cl-improved",
    "Updated": "cl-updated",
    "Fixed": "cl-fixed",
}
BADGE_ORDER = ["New", "Improved", "Updated", "Fixed"]

RELEASE_RE = re.compile(
    r"^#\s+RELEASE UPDATE\s*[-\u2013\u2014]\s*(MID-)?([A-Z]+)\s+(\d{4})\s*$",
    re.I)
VERSION_RE = re.compile(r"^latest version\s*[-:(]?\s*([\w.]+)\)?\s*(?:\((\d+)\))?\s*$", re.I)
ARTICLE_RE = re.compile(r"https?://(?:www\.)?oloid\.help/en/articles/(\d+)[^)\s]*")


# ---------------------------------------------------------------------------
#  Reading the source
# ---------------------------------------------------------------------------

def read(path):
    with io.open(path, encoding="utf-8") as fh:
        text = fh.read().replace("\r\n", "\n")
    return re.sub("[​‌‍﻿]", "", text)    # zero-width characters


def split_intro(text):
    """(intro, body) - the banner and blurb above the first release header."""
    lines = text.split("\n")
    for i, line in enumerate(lines):
        if RELEASE_RE.match(line.strip()):
            return "\n".join(lines[:i]), "\n".join(lines[i:])
    return "", text


def intro_blurb(intro):
    """The product description: the intro minus its image and rules."""
    keep = []
    for line in intro.split("\n"):
        s = line.strip()
        if s.startswith("![") or s == "---":
            continue
        keep.append(line)
    return "\n".join(keep).strip()


def split_releases(body):
    """[(mid, month_index, year, [lines])] for each release header in body."""
    out = []
    current = None
    for line in body.split("\n"):
        m = RELEASE_RE.match(line.strip())
        if m:
            month = MONTHS.index(m.group(2).lower())
            current = (bool(m.group(1)), month, int(m.group(3)), [])
            out.append(current)
            continue
        if current is not None:
            current[3].append(line)
    return out


def classify(text):
    t = text.lower()
    if "bug fix" in t:
        return "Fixed"
    if ("navigation" in t and ("update has been made" in t or "updated" in t)) \
            or "navigation instructions" in t or "updated to reflect" in t:
        return "Updated"
    if "enhancement has been made" in t or "improve" in t or "enhance" in t \
            or "updated" in t or "update has been made" in t:
        return "Improved"
    return "New"


def parse_release(lines):
    """A release's lines -> {version, lead, blocks}.

    blocks is a list of ("section", title) | ("change", title, badge, body) |
    ("bullets", [(text, badge)]) | ("text", markdown), in source order.
    """
    version = None
    lead = []
    blocks = []
    change = None           # [title, [body lines], level]
    bullets = []
    para = []

    def flush_change():
        nonlocal change
        if change:
            body = "\n".join(change[1]).strip()
            blocks.append(("change", change[0], classify(change[0] + " " + body),
                           body, change[2]))
            change = None

    def flush_bullets():
        nonlocal bullets
        if bullets:
            blocks.append(("bullets", [(b, classify(b)) for b in bullets]))
            bullets = []

    def flush_para():
        nonlocal para
        text = "\n".join(para).strip()
        if text:
            if not blocks and change is None:
                lead.append(text)
            else:
                blocks.append(("text", text))
        para = []

    for raw in lines:
        line = raw.rstrip()
        s = line.strip()
        vm = VERSION_RE.match(s)
        if vm and version is None:
            version = vm.group(1) + (" (build %s)" % vm.group(2) if vm.group(2) else "")
            continue
        if s == "---":
            continue
        if re.match(r"^##\s+What'?s New\??\s*$", s, re.I):
            continue
        h = re.match(r"^(#{2,6})\s+(.*?)\s*$", s)
        if h:
            level, title = len(h.group(1)), h.group(2).strip()
            if change is not None:
                flush_change()
            else:
                flush_bullets()
                flush_para()
            if level == 2:
                blocks.append(("section", title))
            elif change is None and level == 4 and title.lower() == "overview":
                continue      # "#### Overview" heads the lead paragraph
            else:
                change = [title.rstrip("."), [], level]
            continue
        if change is not None:
            change[1].append(line)
            continue
        b = re.match(r"^[-*]\s+(.*)$", s)
        if b:
            flush_para()
            bullets.append(b.group(1).strip())
            continue
        if s == "":
            if para:
                flush_para()
            continue
        if bullets and line.startswith("  "):
            bullets[-1] += " " + s
            continue
        flush_bullets()
        para.append(line)
    flush_change()
    flush_bullets()
    flush_para()
    return {"version": version, "lead": "\n\n".join(lead), "blocks": blocks}


