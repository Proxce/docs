def load_article_map(root):
    """{intercom id: '/path'} for every published, non-draft migrated page."""
    path = os.path.join(root, MANIFEST)
    if not os.path.isfile(path):
        return {}
    with io.open(path, encoding="utf-8") as fh:
        data = json.load(fh)
    out = {}
    for rec in data.get("articles") or []:
        p = rec.get("mintlify_path")
        if (rec.get("status") == "written" and p and rec.get("state") == "published"
                and not p.startswith("/drafts/")):
            out[str(rec["id"])] = p
    return out


def fix_text(text, links, stats):
    """Point oloid.help links at migrated pages, tidy link labels."""
    def repl(m):
        aid = m.group(1)
        if aid in links:
            stats["linked"] += 1
            return links[aid]
        stats["external"] += 1
        return re.sub(r"[?&]utm_[^)\s]*", "", m.group(0))

    text = ARTICLE_RE.sub(repl, text)
    text = re.sub(r"\?utm_source=[^)\s]*", "", text)
    text = text.replace("[Read the full guide \u203a]", "[Read the guide \u2192]")
    text = text.replace("[Watch the tutorial \u203a]", "[Watch the tutorial \u2192]")
    text = re.sub(r",\s*,", ",", text)
    # MDX treats { } and < as syntax; Zudoku's sources are plain Markdown.
    text = re.sub(r"(?<!\\)([{}])", r"\\\1", text)
    text = re.sub(r"<(?![A-Za-z/!])", "&lt;", text)
    return text


# ---------------------------------------------------------------------------
#  Writing
# ---------------------------------------------------------------------------

def slugify(text):
    text = re.sub(r"[^\w\s-]", "", text.lower())
    return re.sub(r"[\s_-]+", "-", text).strip("-")


def label_for(rel):
    name = MONTHS[rel["month"]].capitalize()
    return ("Mid-%s %d" if rel["mid"] else "%s %d") % (name, rel["year"])


def badge(kind):
    return '<span className="cl-badge %s">%s</span>' % (BADGES[kind], kind)


def esc_cell(text):
    return text.replace("|", "\\|")


def render_release(rel, product, links, stats):
    label = label_for(rel)
    anchor = slugify(label)
    parsed = rel["parsed"]
    kinds = set()
    rows = []
    body = []
    used_ids = set()

    for block in parsed["blocks"]:
        kind = block[0]
        if kind == "section":
            body += ['<p className="cl-section">%s</p>' % fix_text(block[1], links, stats), ""]
        elif kind == "change" and block[1].rstrip().endswith(":"):
            # "Key updates include:" is a lead-in, not a change of its own
            body += ["**%s**" % fix_text(block[1], links, stats), ""]
            if block[3]:
                body += [fix_text(block[3], links, stats), ""]
        elif kind == "change":
            _k, title, b, text, level = block
            kinds.add(b)
            cid = ("%s-%s" % (anchor, slugify(title)))[:80]
            while cid in used_ids:
                cid += "-x"
            used_ids.add(cid)
            if level <= 3:
                rows.append((title, b, cid))
            heading = "###" if level <= 3 else "####"
            body += ['<span id="%s" className="cl-anchor" />' % cid, "",
                     "%s %s %s" % (heading, fix_text(title, links, stats), badge(b)), ""]
            if text:
                body += [fix_text(text, links, stats), ""]
        elif kind == "bullets":
            body.append('<ul className="cl-list">')
            for text, b in block[1]:
                kinds.add(b)
                rows.append((text.rstrip("."), b, None))
                body.append("  <li>%s %s</li>" % (badge(b), mdx_inline(fix_text(text, links, stats))))
            body += ["</ul>", ""]
        else:
            body += [fix_text(block[1], links, stats), ""]

    stats["changes"] += len(rows)
    tags = [k for k in BADGE_ORDER if k in kinds]
    desc = "Version %s" % parsed["version"] if parsed["version"] else \
        "%d change%s" % (len(rows), "" if len(rows) == 1 else "s")
    out = ['<Update label="%s" description="%s" tags={%s}>' %
           (label, desc, json.dumps(tags)), ""]
    if parsed["lead"]:
        out += [fix_text(parsed["lead"], links, stats), ""]
    if rows and any(r[2] for r in rows):
        out += ["| Change | Type |", "| :--- | :--- |"]
        for title, b, cid in rows:
            cell = "[%s](#%s)" % (esc_cell(title), cid) if cid else esc_cell(title)
            out.append("| %s | %s |" % (fix_text(cell, links, stats), badge(b)))
        out.append("")
    out += body
    out += ["</Update>", ""]
    return "\n".join(out), rows, tags


def mdx_inline(text):
    """Minimal Markdown for text inside a JSX <li>: bold and links."""
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', text)
    return text


def frontmatter(**fields):
    lines = ["---"]
    for k, v in fields.items():
        lines.append("%s: %s" % (k, json.dumps(v, ensure_ascii=False)
                                 if not isinstance(v, bool) else str(v).lower()))
    lines.append("---")
    return "\n".join(lines)


def load_product(zroot, product):
    files = glob.glob(os.path.join(zroot, "pages", "changelog", product["dir"], "*.mdx"))
    releases, blurb = [], ""
    for path in files:
        text = read(path)
        intro, body = split_intro(text)
        for mid, month, year, lines in split_releases(body):
            releases.append({"mid": mid, "month": month, "year": year,
                             "parsed": parse_release(lines),
                             "source": os.path.relpath(path, zroot)})
        if intro_blurb(intro):
            # keep the blurb from the newest month that has one
            stamp = max(((y, m) for _mid, m, y, _l in split_releases(body)), default=(0, 0))
            if not blurb or stamp > blurb[0]:
                blurb = (stamp, intro_blurb(intro))
    releases.sort(key=lambda r: (r["year"], r["month"], r["mid"]), reverse=True)
    return releases, (blurb[1] if blurb else "")


def write_product(root, product, releases, blurb, links, stats, dry_run):
    title = product["title"]
    latest = label_for(releases[0]) if releases else ""
    parts = [
        frontmatter(
            title="%s release notes" % title,
            sidebarTitle=product["short"],
            description="What's new in %s: features, improvements and fixes, "
                        "newest first." % title,
            icon=product["icon"],
            rss=True,
            keywords=["release notes", "changelog", "what's new", product["short"].lower()],
        ),
        "",
        "{/* %s from the Zudoku release notes - edit the source, not this file. */}" % GENERATED_MARK,
        "",
    ]
    if blurb:
        parts += ['<div className="cl-intro">', "", fix_text(blurb, links, stats), "", "</div>", ""]
    parts += ['<p className="cl-meta">Latest release: <strong>%s</strong> &middot; '
              '%d releases &middot; Subscribe with the RSS feed at the top of the page.</p>'
              % (latest, len(releases)), ""]
    summaries = []
    for rel in releases:
        text, rows, tags = render_release(rel, product, links, stats)
        parts.append(text)
        summaries.append({"label": label_for(rel), "anchor": slugify(label_for(rel)),
                          "rows": rows, "tags": tags, "year": rel["year"],
                          "month": rel["month"], "mid": rel["mid"]})
    path = os.path.join(root, OUT_DIR, product["slug"] + ".mdx")
    if not dry_run:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with io.open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(parts).rstrip() + "\n")
    return summaries


def write_landing(root, products, summaries, dry_run):
    out = [
        frontmatter(
            title="Release notes",
            sidebarTitle="Overview",
            description="Every OLOID product release, newest first. Pick a product, "
                        "or scan the latest releases below.",
            icon="megaphone",
            mode="wide",
            keywords=["release notes", "changelog", "what's new"],
        ),
        "",
        "{/* %s - edit the Zudoku source or the script, not this file. */}" % GENERATED_MARK,
        "",
        "Release notes for every OLOID product, newest first. Each product page has a",
        "summary table per release, a badge on every change, and a link to its guide.",
        "",
        '<p className="cl-legend">%s new capability &nbsp; %s change to existing behavior '
        '&nbsp; %s guide or navigation update &nbsp; %s bug fix</p>'
        % tuple(badge(k) for k in BADGE_ORDER),
        "",
    ]
    for family in ("Web portals", "Apps"):
        out += ["## %s" % family, "", "<Columns cols={2}>"]
        for p in products:
            if p["family"] != family:
                continue
            s = summaries.get(p["slug"]) or []
            if not s:
                continue
            icon = ' icon="%s"' % p["icon"]
            if p.get("icon_type"):
                icon += ' iconType="%s"' % p["icon_type"]
            n = sum(len(x["rows"]) for x in s[:1])
            out += ['  <Card title="%s"%s href="/%s/%s">' % (p["title"], icon, OUT_DIR, p["slug"]),
                    "    Latest: **%s** &middot; %d change%s &middot; %d releases"
                    % (s[0]["label"], n, "" if n == 1 else "s", len(s)),
                    "  </Card>"]
        out += ["</Columns>", ""]

    # latest releases across products: the three most recent months
    flat = []
    for p in products:
        for x in summaries.get(p["slug"]) or []:
            flat.append((x["year"], x["month"], x["mid"], p, x))
    months = sorted({(y, m) for y, m, _mid, _p, _x in flat}, reverse=True)[:3]
    out += ["## Latest releases", ""]
    for y, m in months:
        out += ["### %s %d" % (MONTHS[m].capitalize(), y), "",
                "| Product | Changes | Highlights |",
                "| :--- | :--- | :--- |"]
        for yy, mm, mid, p, x in sorted(flat, key=lambda t: (t[0], t[1], t[2]), reverse=True):
            if (yy, mm) != (y, m):
                continue
            highlights = "; ".join(esc_cell(r[0]) for r in x["rows"][:2])
            if len(x["rows"]) > 2:
                highlights += "; +%d more" % (len(x["rows"]) - 2)
            name = p["short"] + (" (mid-month)" if x["mid"] else "")
            out.append("| [%s](/%s/%s#%s) | %s | %s |" % (
                name, OUT_DIR, p["slug"], x["anchor"],
                " ".join(badge(t) for t in x["tags"]) or "-",
                re.sub(r"(?<!\\)([{}])", r"\\\1", highlights) or "-"))
        out.append("")
    path = os.path.join(root, OUT_DIR, "overview.mdx")
    if not dry_run:
        with io.open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(out).rstrip() + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--zudoku", default=os.environ.get("ZUDOKU_ROOT", "O:/zudoku-1"))
    ap.add_argument("--root", default=".")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    root = os.path.abspath(args.root)
    if not os.path.isdir(os.path.join(args.zudoku, "pages", "changelog")):
        sys.exit("no pages/changelog under %s (pass --zudoku)" % args.zudoku)
    links = load_article_map(root)
    stats = {"linked": 0, "external": 0, "changes": 0}
    summaries = {}
    print("%-14s %8s %8s  %s" % ("product", "releases", "changes", "latest"))
    for p in PRODUCTS:
        releases, blurb = load_product(args.zudoku, p)
        before = stats["changes"]
        summaries[p["slug"]] = write_product(root, p, releases, blurb, links, stats, args.dry_run)
        print("%-14s %8d %8d  %s" % (p["slug"], len(releases), stats["changes"] - before,
                                     label_for(releases[0]) if releases else "-"))
    write_landing(root, PRODUCTS, summaries, args.dry_run)
    print("\nguide links: %d pointed at migrated pages, %d kept on oloid.help "
          "(not migrated or not published)" % (stats["linked"], stats["external"]))
    print("%s %s/" % ("would write" if args.dry_run else "written to", OUT_DIR))
    return 0


if __name__ == "__main__":
    sys.exit(main())
