#!/usr/bin/env python3
"""
zudoku_api.py - build the API Reference tab from the Zudoku OpenAPI specs.

    python zudoku_api.py                        # write api-reference/, update navigation.json
    python zudoku_api.py --zudoku D:/zudoku-1   # another checkout
    python zudoku_api.py --dry-run              # report only
    python build_nav.py                         # then rebuild docs.json

The Zudoku project keeps one OpenAPI 3 file per resource under apis/ (Standard
and Advanced) and apis/scoped/ (Scoped), with schemas split into
apis/common/*.json and apis/schemas/*.json. This script bundles each spec
(every $ref inlined) and writes one MDX page per operation: `api:` frontmatter
for the playground, <ParamField> / <ResponseField> for the schema, and
<RequestExample> / <ResponseExample> with cURL, Python and JavaScript.

Why pages and not the spec files: Mintlify serves every file in the repo, so a
spec committed for the Advanced or Scoped APIs could be downloaded by anyone
even though its pages sit behind the login. Generating the pages keeps every
byte of those APIs behind page-level access control. No spec file is written.

Access:
  Standard  public
  Advanced  sign-in plus membership in ACCESS_GROUP (frontmatter `groups:`)
  Scoped    sign-in plus membership in ACCESS_GROUP

The tab is written into navigation.json (its "API Reference" entry is owned by
this script) with `public` set only on the public groups, so build_nav.py
emits the right docs.json. Pages carry GENERATED_MARK; stale ones are deleted.

Examples are scrubbed before they are published: @oloid.ai and personal
addresses become example.com, real tenant names become "acme".
"""

