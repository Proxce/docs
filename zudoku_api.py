def scrub(value):
    if isinstance(value, dict):
        return {k: scrub(v) for k, v in value.items()}
    if isinstance(value, list):
        return [scrub(v) for v in value]
    if not isinstance(value, str):
        return value
    v = re.sub(r"[A-Za-z0-9._%+-]+@(?:oloid\.ai|gmail\.com|company\.com)",
               "jane.doe@example.com", value)
    v = re.sub(r"\bpreview-[0-9A-F]{8,}\b", "acme-0A1B2C3D4E5F", v)
    v = re.sub(r"\bsvc-[0-9a-f]{12,}\b", "svc-<client_id>", v)
    if v in ("preview", "Oloid", "oloid", "demo", "test"):
        return value          # bare words - only tenant fields are rewritten (below)
    return v


SECRET_KEY = re.compile(r"(?i)^(password|pass|pwd|secret|client_?secret|api_?key|x-api-key)$")
TENANT_KEY = re.compile(r"(?i)^tenant(_?name)?$")


def placeholder_for(key):
    return "<client_secret>" if "secret" in key.lower() else \
        "<api_key>" if "key" in key.lower() else "<password>"


def scrub_tenants(value, key=None):
    """Example values: real tenant names -> "acme", secrets -> placeholders."""
    if isinstance(value, dict):
        return {k: scrub_tenants(v, k) for k, v in value.items()}
    if isinstance(value, list):
        return [scrub_tenants(v, key) for v in value]
    if isinstance(value, str) and key:
        if SECRET_KEY.match(key) and value and not value.startswith("<"):
            return placeholder_for(key)
        if TENANT_KEY.match(key):
            return "acme"
    return value


def sanitize_spec(node):
    """Strip example passwords/secrets and real tenant names from schemas.

    Field-level `example`/`default` values are shown on the pages and seed the
    generated request bodies, so they are fixed here, once, at the source.
    """
    if isinstance(node, list):
        for v in node:
            sanitize_spec(v)
        return node
    if not isinstance(node, dict):
        return node
    for pname, pschema in (node.get("properties") or {}).items():
        if not isinstance(pschema, dict):
            continue
        if SECRET_KEY.match(pname):
            for k in ("example", "default", "examples"):
                pschema.pop(k, None)
            pschema["example"] = placeholder_for(pname)
        elif TENANT_KEY.match(pname) and "example" in pschema:
            pschema["example"] = "acme"
    if node.get("in") and node.get("name") and isinstance(node.get("schema"), dict):
        if SECRET_KEY.match(node["name"]):
            node.pop("example", None)
            node["schema"].pop("example", None)
    for v in node.values():
        sanitize_spec(v)
    return node


def mdx(text):
    """Prose from the spec -> safe MDX (no JSX braces, no stray tags)."""
    if not text:
        return ""
    text = scrub(str(text)).strip()
    text = text.replace("\r\n", "\n")
    text = re.sub(r"<br\s*/?>", "\n\n", text)
    parts = re.split(r"(`[^`\n]*`)", text)      # leave inline code untouched
    for i in range(0, len(parts), 2):
        t = parts[i]
        t = re.sub(r"(?<!\\)([{}])", r"\\\1", t)
        t = re.sub(r"<(?![A-Za-z/!])", "&lt;", t)
        t = re.sub(r"<(/?)(?!(?:code|strong|em|b|i|a)\b)([A-Za-z])", r"&lt;\1\2", t)
        parts[i] = t
    return "".join(parts)


def attr(text):
    return str(text).replace("\\", "\\\\").replace('"', "&quot;")


def sentence(text):
    text = re.sub(r"\s+", " ", (text or "").strip()).rstrip(".")
    return text[:1].upper() + text[1:] if text else text


def slugify(text):
    text = re.sub(r"[^\w\s-]", " ", text.lower())
    return re.sub(r"[\s_-]+", "-", text).strip("-")


