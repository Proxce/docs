def op_slug(op, method, path, used):
    base = op.get("operationId")
    base = slugify(re.sub(r"([a-z0-9])([A-Z])", r"\1-\2", base)) if base else ""
    if not base:
        base = slugify("%s %s" % (method, path.replace("{", "by ").replace("}", "")))
    slug, n = base, 2
    while slug in used:
        slug, n = "%s-%d" % (base, n), n + 1
    used.add(slug)
    return slug


def write(path, text, written, dry_run):
    written.add(os.path.normpath(path))
    if dry_run:
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with io.open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text if text.endswith("\n") else text + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--zudoku", default=os.environ.get("ZUDOKU_ROOT", "O:/zudoku-1"))
    ap.add_argument("--root", default=".")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    root = os.path.abspath(args.root)
    apis = os.path.join(args.zudoku, "apis")
    if not os.path.isdir(apis):
        sys.exit("no apis/ under %s (pass --zudoku)" % args.zudoku)

    written = set()
    nav_groups = [{"group": "Get started", "icon": "rocket", "public": True,
                   "pages": ["%s/get-started/introduction" % OUT_DIR,
                             "%s/get-started/authentication" % OUT_DIR,
                             "%s/get-started/errors" % OUT_DIR]}]
    stats = {}
    error_schema, error_examples = None, []
    login_example, login_response = None, None

    for api_set in SETS:
        set_dir = api_set["key"]
        resources, servers, sub_groups, count = [], [], [], 0
        for spec_name, resource, icon in api_set["specs"]:
            path = os.path.join(apis, spec_name)
            spec = sanitize_spec(bundle(load_file(path), os.path.normpath(path)))
            server = ((spec.get("servers") or [{}])[0].get("url") or
                      "https://api.oloidpreview.com").rstrip("/")
            for s in spec.get("servers") or []:
                if s.get("url") and s["url"].rstrip("/") not in servers \
                        and "previewoloid" not in s["url"]:
                    servers.append(s["url"].rstrip("/"))
            res_slug = slugify(resource)
            used, ops, pages = set(), [], []
            entries = []
            for p, item in (spec.get("paths") or {}).items():
                for method, op in item.items():
                    if method in METHOD_ORDER and isinstance(op, dict):
                        entries.append((p, method, op, item))
            for p, method, op, item in entries:
                slug = op_slug(op, method, p, used)
                if spec_name.endswith("logins.yaml") and p == "/login":
                    slug = "login"
                title, text = operation_page(api_set, resource, spec_name, spec, server,
                                             p, method, op, item)
                write(os.path.join(root, OUT_DIR, set_dir, res_slug, slug + ".mdx"),
                      text, written, args.dry_run)
                ops.append((title, method.upper(), p, slug, needs_auth(spec, op)))
                pages.append("%s/%s/%s/%s" % (OUT_DIR, set_dir, res_slug, slug))
                if spec_name == "logins.yaml" and p == "/login" and login_example is None:
                    content = (op.get("requestBody") or {}).get("content") or {}
                    login_example = clean_example(media_example(content)[1])
                    okc = ((op.get("responses") or {}).get("200") or {}).get("content")
                    login_response = clean_example(media_example(okc)[1])
                if spec_name == "users.yaml" and error_schema is None:
                    for code in ("400", "401"):
                        r = (op.get("responses") or {}).get(code) or {}
                        c = (r.get("content") or {}).get("application/json") or {}
                        if c.get("schema"):
                            error_schema = error_schema or flatten(c["schema"])
                            error_examples.append(("%s %s" % (code, STATUS_TEXT[code]),
                                                   clean_example(media_example(r["content"])[1])))
            write(os.path.join(root, OUT_DIR, set_dir, res_slug, "overview.mdx"),
                  resource_page(api_set, resource, icon, spec, server, ops, set_dir, res_slug),
                  written, args.dry_run)
            count += len(ops)
            resources.append((resource, icon, "/%s/%s/%s/overview" % (OUT_DIR, set_dir, res_slug),
                              len(ops)))
            sub_groups.append({"group": resource, "icon": icon,
                               "pages": ["%s/%s/%s/overview" % (OUT_DIR, set_dir, res_slug)] + pages})
            print("  %-9s %-16s %3d endpoints" % (set_dir, resource, len(ops)))
        write(os.path.join(root, OUT_DIR, set_dir, "overview.mdx"),
              set_page(api_set, resources, servers), written, args.dry_run)
        stats[set_dir] = count
        # `pages: []` - without it build_nav.py would list api-reference/*.mdx
        # (the Get started pages) in this group a second time.
        group = {"group": api_set["title"], "icon": api_set["icon"], "pages": [],
                 "groups": [{"group": "Overview", "icon": "compass",
                             "pages": ["%s/%s/overview" % (OUT_DIR, set_dir)]}] + sub_groups}
        if api_set["public"]:
            group["public"] = True
        else:
            group["$comment"] = ("Not public: pages need a sign-in and the '%s' group "
                                 "(frontmatter `groups`)." % ACCESS_GROUP)
        nav_groups.append(group)

    write(os.path.join(root, OUT_DIR, "get-started", "introduction.mdx"), landing_page(stats), written, args.dry_run)
    write(os.path.join(root, OUT_DIR, "get-started", "authentication.mdx"),
          auth_page(login_example or {}, login_response or {}), written, args.dry_run)
    write(os.path.join(root, OUT_DIR, "get-started", "errors.mdx"), errors_page(error_schema, error_examples[:2]),
          written, args.dry_run)

    # stale pages from an earlier run
    stale = []
    for dirpath, _dirs, files in os.walk(os.path.join(root, OUT_DIR)):
        for name in files:
            full = os.path.normpath(os.path.join(dirpath, name))
            if name.endswith(".mdx") and full not in written:
                with io.open(full, encoding="utf-8") as fh:
                    if GENERATED_MARK in fh.read():
                        stale.append(full)
    for path in stale:
        if not args.dry_run:
            os.remove(path)

    # navigation.json: this script owns the API Reference tab
    nav_path = os.path.join(root, NAV_FILE)
    with io.open(nav_path, encoding="utf-8") as fh:
        nav = json.load(fh)
    tab = {"tab": TAB_NAME, "icon": "code", "slug": OUT_DIR, "group_menu": True,
           "$comment": "Written by zudoku_api.py from the Zudoku OpenAPI specs - re-run it "
                       "instead of editing this entry. Standard is public; Advanced and Scoped "
                       "need a sign-in and the '%s' group." % ACCESS_GROUP,
           "groups": nav_groups}
    names = [t.get("tab") for t in nav["tabs"]]
    if TAB_NAME in names:
        nav["tabs"][names.index(TAB_NAME)] = tab
    else:
        at = names.index("Resources") if "Resources" in names else len(names) - 1
        nav["tabs"].insert(at, tab)
    if not args.dry_run:
        with io.open(nav_path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(json.dumps(nav, indent=2, ensure_ascii=False) + "\n")

    # docs.json: the playground only shows a token field on MDX `api:` pages
    # when the site-level API auth is set - `authMethod` in frontmatter alone
    # renders no input, so every protected call went out without a token.
    docs_path = os.path.join(root, "docs.json")
    with io.open(docs_path, encoding="utf-8") as fh:
        docs = json.load(fh)
    want = {"mdx": {"auth": {"method": "bearer"}}, "playground": {"display": "interactive"}}
    api_cfg = docs.get("api") or {}
    merged = dict(api_cfg, mdx=dict(api_cfg.get("mdx") or {}, **want["mdx"]),
                  playground=dict(want["playground"], **(api_cfg.get("playground") or {})))
    if merged != api_cfg and not args.dry_run:
        docs["api"] = merged
        with io.open(docs_path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(json.dumps(docs, indent=2, ensure_ascii=False) + "\n")

    print("\n%d pages %s, %d stale removed; endpoints: %s"
          % (len(written), "would be written" if args.dry_run else "written", len(stale),
             ", ".join("%s %d" % kv for kv in stats.items())))
    print("navigation.json %s - run build_nav.py next"
          % ("unchanged (dry run)" if args.dry_run else "updated"))
    return 0


