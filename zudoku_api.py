# Examples built from a schema (when the spec gives none) stay readable:
# required fields first, at most SYNTH_KEYS per object, SYNTH_DEPTH levels.
SYNTH_DEPTH = 3
SYNTH_KEYS = 12


def synth(schema, depth=0, name=""):
    schema = flatten(schema)
    if "example" in schema:
        return schema["example"]
    if schema.get("examples") and isinstance(schema["examples"], list):
        return schema["examples"][0]
    if schema.get("enum"):
        return schema["enum"][0]
    if "default" in schema:
        return schema["default"]
    if depth > SYNTH_DEPTH:
        return {}
    opts = schema.get("oneOf") or schema.get("anyOf")
    if opts:
        return synth(opts[0], depth + 1, name)
    t = schema.get("type")
    if isinstance(t, list):
        t = next((x for x in t if x != "null"), t[0])
    if t == "array" or "items" in schema:
        return [synth(schema.get("items") or {}, depth + 1, name)]
    if t == "object" or schema.get("properties"):
        props = schema.get("properties") or {}
        required = [k for k in (schema.get("required") or []) if k in props]
        keys = required + [k for k in props if k not in required]
        return {k: synth(props[k], depth + 1, k) for k in keys[:SYNTH_KEYS]}
    if t == "integer":
        return 0
    if t == "number":
        return 0.0
    if t == "boolean":
        return True
    fmt = schema.get("format")
    if fmt == "date-time":
        return "2026-01-15T10:30:00Z"
    if fmt == "date":
        return "2026-01-15"
    if fmt == "email" or "email" in name.lower():
        return "jane.doe@example.com"
    if fmt in ("uuid",):
        return "3fa85f64-5717-4562-b3fc-2c963f66afa6"
    return "string"


def media_example(content):
    """First JSON example a media object offers, or None."""
    if not content:
        return None, None
    ctype = "application/json" if "application/json" in content else next(iter(content))
    media = content.get(ctype) or {}
    if "example" in media:
        return ctype, media["example"]
    if media.get("examples"):
        first = next(iter(media["examples"].values()))
        if isinstance(first, dict) and "value" in first:
            return ctype, first["value"]
    schema = media.get("schema")
    if schema:
        return ctype, synth(schema)
    return ctype, None


def clean_example(value):
    return scrub_tenants(scrub(value))


