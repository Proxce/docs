def curl(method, url, auth, ctype, body):
    lines = ["curl --request %s \\" % method, "  --url '%s'" % url]
    if auth:
        lines[-1] += " \\"
        lines.append("  --header 'Authorization: Bearer %s'" % TOKEN)
    if body is not None:
        lines[-1] += " \\"
        if ctype and "multipart" in ctype:
            parts = list(body.items()) if isinstance(body, dict) else []
            for i, (k, v) in enumerate(parts):
                val = "@face.jpg" if isinstance(v, str) and v == "string" else v
                lines.append("  --form '%s=%s'%s" % (k, val, " \\" if i < len(parts) - 1 else ""))
        else:
            lines.append("  --header 'Content-Type: application/json' \\")
            data = json.dumps(body, indent=2, ensure_ascii=False).replace("'", "'\\''")
            lines.append("  --data '%s'" % data.replace("\n", "\n  "))
    return "\n".join(lines)


def python_sample(method, url, auth, ctype, body):
    lines = ["import requests", "", 'url = "%s"' % url]
    headers = {}
    if auth:
        headers["Authorization"] = "Bearer %s" % TOKEN
    lines.append("headers = %s" % json.dumps(headers, indent=4))
    args = "url, headers=headers"
    if body is not None and not (ctype and "multipart" in ctype):
        lines.append("payload = %s" % pyrepr(body))
        args += ", json=payload"
    elif body is not None:
        lines.append('files = {"file": open("face.jpg", "rb")}')
        args += ", files=files"
    lines += ["", "response = requests.%s(%s)" % (method.lower(), args), "print(response.json())"]
    return "\n".join(lines)


def pyrepr(value):
    text = json.dumps(value, indent=4, ensure_ascii=False)
    return re.sub(r"\b(true|false|null)\b",
                  lambda m: {"true": "True", "false": "False", "null": "None"}[m.group(1)], text)


def js_sample(method, url, auth, ctype, body):
    headers = {}
    if auth:
        headers["Authorization"] = "Bearer %s" % TOKEN
    lines = []
    opts = ["  method: '%s'," % method]
    if body is not None and not (ctype and "multipart" in ctype):
        headers["Content-Type"] = "application/json"
    if headers:
        opts.append("  headers: %s," % json.dumps(headers, indent=4).replace("\n", "\n  ")
                    .replace("\n  }", "\n  }"))
    if body is not None and not (ctype and "multipart" in ctype):
        opts.append("  body: JSON.stringify(%s)," % json.dumps(body, indent=4, ensure_ascii=False)
                    .replace("\n", "\n  "))
    elif body is not None:
        lines += ["const form = new FormData();", "form.append('file', fileInput.files[0]);", ""]
        opts.append("  body: form,")
    lines += ["const response = await fetch('%s', {" % url] + opts + ["});",
              "const data = await response.json();", "console.log(data);"]
    return "\n".join(lines)


