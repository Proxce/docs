def frontmatter(fields):
    out = ["---"]
    for k, v in fields.items():
        if v is None:
            continue
        if isinstance(v, bool):
            out.append("%s: %s" % (k, str(v).lower()))
        else:
            out.append("%s: %s" % (k, json.dumps(v, ensure_ascii=False)))
    out.append("---")
    return "\n".join(out)


def access_fields(api_set):
    return {} if api_set["public"] else {"groups": [ACCESS_GROUP]}


def needs_auth(spec, op):
    sec = op.get("security", spec.get("security"))
    return bool(sec) and any(s for s in sec)


STATUS_TEXT = {"200": "OK", "201": "Created", "204": "No Content", "400": "Bad Request",
               "401": "Unauthorized", "403": "Forbidden", "404": "Not Found",
               "409": "Conflict", "422": "Unprocessable Entity",
               "500": "Internal Server Error", "502": "Bad Gateway"}


def operation_page(api_set, resource, spec_name, spec, server, path, method, op, item):
    m = method.upper()
    title = TITLE_OVERRIDES.get((spec_name, m, path)) or sentence(op.get("summary")) \
        or "%s %s" % (m, path)
    description = sentence(op.get("description") or "")
    if description.lower() == title.lower():
        description = ""
    auth = needs_auth(spec, op)

    params = list(item.get("parameters") or []) + list(op.get("parameters") or [])
    seen, merged = set(), []
    for p in params:
        key = (p.get("in"), p.get("name"))
        if key in seen:
            continue
        seen.add(key)
        merged.append(p)

    body_lines = []
    groups = {"path": [], "query": [], "header": [], "cookie": []}
    for p in merged:
        loc = p.get("in")
        if loc == "header" and p.get("name", "").lower() == "authorization" and auth:
            continue                      # the playground's bearer field covers it
        if loc == "header" and p.get("name", "").lower() == "authorization":
            pass
        groups.setdefault(loc, []).append(p)

    _BUDGET[0] = FIELD_BUDGET
    for loc in ("path", "query", "header", "cookie"):
        for p in groups.get(loc) or []:
            schema = flatten(p.get("schema") or {})
            attrs = ['%s="%s"' % (loc, attr(p["name"])), 'type="%s"' % type_label(schema)]
            if p.get("required") or loc == "path":
                attrs.append("required")
            if schema.get("default") is not None:
                attrs.append('default="%s"' % attr(scrub(str(schema["default"]))))
            prop = dict(schema)
            if p.get("description"):
                prop["description"] = p["description"]
            if p.get("example") is not None:
                prop["example"] = p["example"]
            write_field("ParamField", attrs, prop, 0, body_lines, "", loc)

    req_ctype, req_body = None, None
    rb = op.get("requestBody")
    if rb:
        content = rb.get("content") or {}
        req_ctype, req_body = media_example(content)
        req_body = clean_example(req_body)
        schema = flatten((content.get(req_ctype) or {}).get("schema") or {})
        if schema.get("properties"):
            _BUDGET[0] = FIELD_BUDGET
            render_fields(schema, "ParamField", "body", 0, body_lines)
        elif schema:
            write_field("ParamField", ['body="body"', 'type="%s"' % type_label(schema),
                                       "required" if rb.get("required") else ""],
                        schema, 0, body_lines, "", "body")

    responses = op.get("responses") or {}
    ok = next((c for c in ("200", "201", "202", "204") if c in responses), None)
    resp_lines = []
    if ok:
        content = (responses[ok] or {}).get("content") or {}
        ctype = "application/json" if "application/json" in content else next(iter(content), None)
        schema = flatten((content.get(ctype) or {}).get("schema") or {}) if ctype else {}
        if schema.get("properties"):
            _BUDGET[0] = FIELD_BUDGET
            render_fields(schema, "ResponseField", None, 0, resp_lines)
        elif schema:
            write_field("ResponseField", ['name="response"', 'type="%s"' % type_label(schema)],
                        schema, 0, resp_lines, "", None)

    # samples
    path_example = path
    query = [(p["name"], "{%s}" % p["name"]) for p in groups.get("query") or [] if p.get("required")]
    url = sample_url(server, path_example, query)
    samples = [("bash", "cURL", curl(m, url, auth, req_ctype, req_body)),
               ("python", "Python", python_sample(m, url, auth, req_ctype, req_body)),
               ("javascript", "JavaScript", js_sample(m, url, auth, req_ctype, req_body))]

    resp_examples = []
    for code, resp in responses.items():
        resp = resp or {}
        ctype, ex = media_example(resp.get("content"))
        if ex is None:
            continue
        label = "%s %s" % (code, STATUS_TEXT.get(str(code), ""))
        resp_examples.append((label.strip(), json.dumps(clean_example(ex), indent=2,
                                                         ensure_ascii=False)))

    lines = [frontmatter(dict(
        title=title,
        description=description or None,
        api="%s %s%s" % (m, server.rstrip("/"), path),
        authMethod="bearer" if auth else "none",
        keywords=["api", resource.lower(), api_set["title"].lower(), path],
        **access_fields(api_set))), "",
        "{/* %s from %s - edit the Zudoku spec, not this file. */}" % (GENERATED_MARK, spec_name),
        ""]
    if not auth:
        lines += ["<Note>This call needs no token. Use it to get the ID token every other "
                  "call sends as `Authorization: Bearer <id_token>`.</Note>", ""]
    lines += body_lines
    if resp_lines:
        lines += ["## Response", ""] + resp_lines
    lines += ["<RequestExample>", ""]
    for lang, label, code in samples:
        lines += ["```%s %s" % (lang, label), code, "```", ""]
    lines += ["</RequestExample>", ""]
    if resp_examples:
        lines += ["<ResponseExample>", ""]
        for label, code in resp_examples:
            lines += ["```json %s" % label, code, "```", ""]
        lines += ["</ResponseExample>", ""]
    text = "\n".join(lines)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return title, text.rstrip() + "\n"


