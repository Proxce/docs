def type_label(schema):
    schema = flatten(schema)
    t = schema.get("type")
    if isinstance(t, list):
        t = next((x for x in t if x != "null"), t[0])
    if t == "array":
        item = flatten(schema.get("items") or {})
        it = item.get("type") or ("object" if item.get("properties") else "any")
        return "%s[]" % it
    if not t:
        if schema.get("properties"):
            return "object"
        if schema.get("oneOf") or schema.get("anyOf"):
            return "object"
        return "any"
    if t == "string" and schema.get("format") == "binary":
        return "file"
    return t


def constraints(schema):
    schema = flatten(schema)
    bits = []
    if schema.get("enum"):
        vals = ", ".join("`%s`" % v for v in schema["enum"][:12])
        bits.append("Available options: %s" % vals)
    if schema.get("format") and schema.get("format") != "binary":
        bits.append("Format: `%s`" % schema["format"])
    if schema.get("pattern"):
        bits.append("Pattern: `%s`" % schema["pattern"])
    lo, hi = schema.get("minLength"), schema.get("maxLength")
    if lo is not None and hi is not None and lo == hi:
        bits.append("Length: %s" % lo)
    else:
        if lo:
            bits.append("Minimum length: %s" % lo)
        if hi:
            bits.append("Maximum length: %s" % hi)
    if schema.get("minimum") is not None:
        bits.append("Minimum: %s" % schema["minimum"])
    if schema.get("maximum") is not None:
        bits.append("Maximum: %s" % schema["maximum"])
    ex = schema.get("example")
    if ex is not None and not isinstance(ex, (dict, list)) and len(str(ex)) < 80:
        bits.append("Example: `%s`" % scrub(str(ex)).replace("`", "'"))
    return bits


def children_of(schema):
    """(kind, payload) for what nests under a field: properties, options or none."""
    schema = flatten(schema)
    if schema.get("type") == "array" or "items" in schema:
        schema = flatten(schema.get("items") or {})
    if schema.get("properties"):
        return "props", schema
    opts = schema.get("oneOf") or schema.get("anyOf")
    if opts:
        return "options", [flatten(o) for o in opts]
    return None, None


def render_fields(schema, tag, loc, depth, out, indent=""):
    """Emit <ParamField>/<ResponseField> for each property of an object schema."""
    schema = flatten(schema)
    required = set(schema.get("required") or [])
    for name, prop in (schema.get("properties") or {}).items():
        prop = flatten(prop)
        if prop.get("readOnly") and tag == "ParamField":
            continue
        attrs = []
        if tag == "ParamField":
            attrs.append('%s="%s"' % (loc, attr(name)))
        else:
            attrs.append('name="%s"' % attr(name))
        attrs.append('type="%s"' % type_label(prop))
        if name in required:
            attrs.append("required")
        if prop.get("default") is not None and not isinstance(prop["default"], (dict, list)):
            attrs.append('default="%s"' % attr(scrub(str(prop["default"]))))
        if prop.get("deprecated"):
            attrs.append("deprecated")
        write_field(tag, attrs, prop, depth, out, indent, loc)


# Field rendering limits: nesting depth (0 = top-level field) and a per-section
# field budget, reset for each request body and each response. Without them the
# largest pages ran past 1 MB of nested <ResponseField>s.
MAX_DEPTH = 3
FIELD_BUDGET = 250
_BUDGET = [FIELD_BUDGET]


def write_field(tag, attrs, prop, depth, out, indent, loc):
    _BUDGET[0] -= 1
    out.append("%s<%s %s>" % (indent, tag, " ".join(a for a in attrs if a)))
    desc = mdx(prop.get("description") or prop.get("title") or "")
    if desc:
        out.append(indent + "  " + desc.replace("\n", "\n" + indent + "  "))
    bits = constraints(prop)
    if bits:
        if desc:
            out.append("")
        out.append(indent + "  " + mdx("; ".join(bits)))
    kind, payload = children_of(prop)
    if kind and (depth >= MAX_DEPTH or _BUDGET[0] <= 0):
        # Deep or very large schemas (the User object nests for pages) are
        # cut here; the response/request example still shows the full shape.
        out.append("")
        out.append(indent + "  Nested fields are shown in the example.")
        kind = None
    if kind:
        out.append("")
        if kind == "props":
            out.append('%s  <Expandable title="properties">' % indent)
            render_fields(payload, tag, loc, depth + 1, out, indent + "    ")
            out.append("%s  </Expandable>" % indent)
        else:
            for i, opt in enumerate(payload, 1):
                title = opt.get("title") or "option %d" % i
                out.append('%s  <Expandable title="%s">' % (indent, attr(title)))
                if opt.get("properties"):
                    render_fields(opt, tag, loc, depth + 1, out, indent + "    ")
                else:
                    out.append("%s    %s" % (indent, mdx(opt.get("description") or type_label(opt))))
                out.append("%s  </Expandable>" % indent)
    out.append("%s</%s>" % (indent, tag))
    out.append("")


