_FILES = {}


class _Loader(yaml.SafeLoader):
    """SafeLoader that keeps dates and timestamps as the strings they were
    written as - examples are shown verbatim and must stay JSON-serialisable."""


_Loader.yaml_implicit_resolvers = {
    k: [(tag, rx) for tag, rx in v if tag != "tag:yaml.org,2002:timestamp"]
    for k, v in yaml.SafeLoader.yaml_implicit_resolvers.items()
}


def load_file(path):
    path = os.path.normpath(path)
    if path not in _FILES:
        with io.open(path, encoding="utf-8") as fh:
            _FILES[path] = json.load(fh) if path.endswith(".json") else yaml.load(fh, Loader=_Loader)
    return _FILES[path]


def pointer(doc, frag):
    node = doc
    for part in frag.lstrip("/").split("/"):
        if not part:
            continue
        part = part.replace("~1", "/").replace("~0", "~")
        node = node[part]
    return node


def bundle(node, base, stack=()):
    """Inline every $ref under `node`. `base` is the file the node came from.

    A ref seen again inside itself (a recursive schema) is cut to a stub so
    the page cannot grow without bound.
    """
    if isinstance(node, list):
        return [bundle(v, base, stack) for v in node]
    if not isinstance(node, dict):
        return node
    if "$ref" in node and isinstance(node["$ref"], str):
        ref = node["$ref"]
        file_part, _, frag = ref.partition("#")
        target_file = os.path.normpath(os.path.join(os.path.dirname(base), file_part)) \
            if file_part else base
        key = (target_file, frag)
        if key in stack:
            return {"type": "object", "description": "Recursive - same shape as its parent."}
        target = load_file(target_file)
        if frag:
            target = pointer(target, frag)
        merged = bundle(target, target_file, stack + (key,))
        extra = {k: v for k, v in node.items() if k != "$ref"}
        if extra and isinstance(merged, dict):
            merged = dict(merged, **bundle(extra, base, stack))
        return merged
    return {k: bundle(v, base, stack) for k, v in node.items()}


def flatten(schema):
    """Merge allOf into one object schema; leave oneOf/anyOf for the renderer."""
    if not isinstance(schema, dict):
        return {}
    if "allOf" in schema:
        out = {k: v for k, v in schema.items() if k != "allOf"}
        props, required = dict(out.get("properties") or {}), list(out.get("required") or [])
        for part in schema["allOf"]:
            part = flatten(part)
            props.update(part.get("properties") or {})
            required += part.get("required") or []
            for k in ("type", "description", "example"):
                out.setdefault(k, part.get(k))
        out["properties"], out["required"] = props, required
        out.setdefault("type", "object")
        return {k: v for k, v in out.items() if v is not None}
    return schema


