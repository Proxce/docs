class IntercomError(RuntimeError):
    pass


def request_json(url, token, timeout=30):
    req = urllib.request.Request(url, method="GET")
    req.add_header("Authorization", "Bearer %s" % token)
    req.add_header("Accept", "application/json")
    req.add_header("Intercom-Version", API_VERSION)
    req.add_header("User-Agent", "oloid-intercom-to-mintlify/1.0")

    delay = RETRY_BACKOFF
    for attempt in range(1, MAX_RETRIES + 1):
        try:
            with urllib.request.urlopen(req, timeout=timeout) as resp:
                return json.loads(resp.read().decode("utf-8"))
        except urllib.error.HTTPError as exc:
            body = exc.read().decode("utf-8", "replace")[:400]
            if exc.code in (401, 403):
                raise IntercomError(
                    "Auth failed (HTTP %s). Check API_KEY at the top of this file "
                    "or $INTERCOM_API_KEY.\n%s" % (exc.code, body)
                )
            if exc.code == 404:
                raise IntercomError("Article not found (HTTP 404): %s" % url)
            if exc.code == 429 or 500 <= exc.code < 600:
                sys.stderr.write("  HTTP %s, retry in %.0fs (%d/%d)\n"
                                 % (exc.code, delay, attempt, MAX_RETRIES))
                time.sleep(delay)
                delay *= 2
                continue
            raise IntercomError("HTTP %s from %s\n%s" % (exc.code, url, body))
        except (urllib.error.URLError, TimeoutError) as exc:
            sys.stderr.write("  network error (%s), retry in %.0fs (%d/%d)\n"
                             % (exc, delay, attempt, MAX_RETRIES))
            time.sleep(delay)
            delay *= 2
    raise IntercomError("Gave up on %s after %d attempts" % (url, MAX_RETRIES))


def fetch_article(article_id, token):
    url = "%s/articles/%s" % (API_ROOT, article_id)
    sys.stderr.write("GET %s\n" % url)
    return request_json(url, token)


