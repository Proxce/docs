# Reformatting pages that are already on disk
# --------------------------------------------------------------------------
#  Re-running the importer needs an Intercom token. --reformat applies the
#  template to the .mdx files already in the repo instead, so a change to the
#  document format can be rolled out without re-fetching every article.
# --------------------------------------------------------------------------

GENERATED_MARKER = "Generated by intercom_to_mintlify.py"


def split_frontmatter(text):
    """Return (frontmatter_lines, body). Frontmatter here is always generated
    by this script, so a line scan is enough and avoids a YAML dependency."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return [], text
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return lines[1:i], "\n".join(lines[i + 1:])
    return [], text


def set_frontmatter_keywords(fm_lines, keywords):
    """Replace the keywords block, or leave it alone when there is nothing new.

    On a second --reformat run the body no longer holds a Keywords section
    (the first run moved it up here), so an empty list must not be read as
    "this page has no keywords".
    """
    if not keywords:
        return fm_lines
    out, in_keywords = [], False
    for line in fm_lines:
        if re.match(r"^keywords[ \t]*:", line):
            in_keywords = True
            continue
        if in_keywords:
            if re.match(r"^[ \t]+-[ \t]", line):
                continue
            in_keywords = False
        out.append(line)
    out.append("keywords:")
    out += ["  - %s" % json.dumps(k) for k in keywords]
    return out


def reformat_file(path, dry_run):
    with open(path, "r", encoding="utf-8") as fh:
        original = fh.read()
    if GENERATED_MARKER not in original:
        return None

    fm_lines, body = split_frontmatter(original)
    body, keywords, audit = apply_template(body)
    fm_lines = set_frontmatter_keywords(fm_lines, keywords)
    rebuilt = "---\n" + "\n".join(fm_lines) + "\n---\n\n" + body + "\n"

    changed = rebuilt != original
    if changed and not dry_run:
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(rebuilt)
    return {"path": path, "changed": changed, "keywords": keywords, "audit": audit}


def reformat_tree(root, dry_run):
    results = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames
                       if d not in (".git", "node_modules", "__pycache__", "images")]
        for name in sorted(filenames):
            if not name.endswith(".mdx"):
                continue
            row = reformat_file(os.path.join(dirpath, name), dry_run)
            if row:
                row["rel"] = os.path.relpath(row["path"], root).replace(os.sep, "/")
                results.append(row)
    return results


