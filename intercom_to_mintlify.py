def short_title(title, limit=48):
    """Intercom titles run well past 100 characters, which wrecks the sidebar.

    "Oloid Vault (Chrome / Chromium) - How to Create and Configure ..."
      -> "How to Create and Configure Oloid Vault..."
    """
    text = re.sub(r"\s+", " ", title).strip()
    # drop a leading "Product - " qualifier; the menu already carries that context
    if " - " in text:
        head, _, tail = text.partition(" - ")
        if len(head) <= 60 and len(tail) >= 12:
            text = tail.strip()
    if len(text) <= limit:
        return text
    cut = text[:limit].rsplit(" ", 1)[0].rstrip(" ,.;:-")
    return (cut or text[:limit]) + "..."


def first_sentence(body_mdx, limit=160):
    """Fallback description: the first real prose line of the article."""
    for line in (body_mdx or "").splitlines():
        line = line.strip()
        if not line or line.startswith(("#", "<", "|", "-", ">", "!", "`", "1.")):
            continue
        line = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", line)   # unwrap links
        line = re.sub(r"[*`]+", "", line)                        # drop emphasis
        line = re.sub(r"&#?\w+;", " ", line)                     # drop entities
        line = re.sub(r"\s+", " ", line).strip()
        if len(line) < 25:
            continue
        if len(line) > limit:
            line = line[:limit].rsplit(" ", 1)[0].rstrip(" ,.;:-") + "..."
        return line
    return ""


def build_mdx(article, body_mdx, icon=None, keywords=None):
    title = html.unescape((article.get("title") or "Untitled").strip())
    desc = html.unescape((article.get("description") or "").strip())
    desc = re.sub(r"\s+", " ", desc)[:160] or first_sentence(body_mdx)

    fm = ["---", "title: %s" % json.dumps(title)]
    sidebar = short_title(title)
    if sidebar and sidebar != title:
        fm.append("sidebarTitle: %s" % json.dumps(sidebar))
    if desc:
        fm.append("description: %s" % json.dumps(desc))
    if icon:
        fm.append("icon: %s" % json.dumps(icon))
    if keywords:
        # indexed by Mintlify search; deliberately renders nothing on the page
        fm.append("keywords:")
        fm += ["  - %s" % json.dumps(k) for k in keywords]
    fm += [
        "---",
        "",
        "{/* Source: Intercom article %s - %s */}" % (article.get("id"), article.get("url") or ""),
        "{/* Generated by intercom_to_mintlify.py - re-running overwrites this file. */}",
        "",
        "",
    ]
    return "\n".join(fm) + (body_mdx or "_This article has no body content in Intercom._") + "\n"


# --------------------------------------------------------------------------
# Reformatting pages that are already on disk
# --------------------------------------------------------------------------
#  Re-running the importer needs an Intercom token. --reformat applies the
#  template to the .mdx files already in the repo instead, so a change to the
#  document format can be rolled out without re-fetching every article.
# --------------------------------------------------------------------------

GENERATED_MARKER = "Generated by intercom_to_mintlify.py"


def split_frontmatter(text):
    """Return (frontmatter_lines, body). Frontmatter here is always generated
    by this script, so a line scan is enough and avoids a YAML dependency."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return [], text
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return lines[1:i], "\n".join(lines[i + 1:])
    return [], text


def set_frontmatter_keywords(fm_lines, keywords):
    """Replace the keywords block, or leave it alone when there is nothing new.

    On a second --reformat run the body no longer holds a Keywords section
    (the first run moved it up here), so an empty list must not be read as
    "this page has no keywords".
    """
    if not keywords:
        return fm_lines
    out, in_keywords = [], False
    for line in fm_lines:
        if re.match(r"^keywords[ \t]*:", line):
            in_keywords = True
            continue
        if in_keywords:
            if re.match(r"^[ \t]+-[ \t]", line):
                continue
            in_keywords = False
        out.append(line)
    out.append("keywords:")
    out += ["  - %s" % json.dumps(k) for k in keywords]
    return out


def reformat_file(path, dry_run):
    with open(path, "r", encoding="utf-8") as fh:
        original = fh.read()
    if GENERATED_MARKER not in original:
        return None

    fm_lines, body = split_frontmatter(original)
    body, keywords, audit = apply_template(body)
    fm_lines = set_frontmatter_keywords(fm_lines, keywords)
    rebuilt = "---\n" + "\n".join(fm_lines) + "\n---\n\n" + body + "\n"

    changed = rebuilt != original
    if changed and not dry_run:
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(rebuilt)
    return {"path": path, "changed": changed, "keywords": keywords, "audit": audit}


def reformat_tree(root, dry_run):
    results = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames
                       if d not in (".git", "node_modules", "__pycache__", "images")]
        for name in sorted(filenames):
            if not name.endswith(".mdx"):
                continue
            row = reformat_file(os.path.join(dirpath, name), dry_run)
            if row:
                row["rel"] = os.path.relpath(row["path"], root).replace(os.sep, "/")
                results.append(row)
    return results


