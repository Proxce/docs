def slugify(value, max_len=70):
    value = html.unescape(str(value or "")).lower()
    value = re.sub(r"[^a-z0-9]+", "-", value).strip("-")
    if len(value) > max_len:
        value = value[:max_len].rsplit("-", 1)[0]
    return value or "untitled"


def page_slug(article):
    """Prefer the slug Intercom already uses in the public URL."""
    url = article.get("url") or ""
    tail = urllib.parse.urlparse(url).path.rstrip("/").split("/")[-1]
    tail = re.sub(r"^\d+-", "", tail)  # drop the leading article id
    return slugify(tail or article.get("title"))


