    if not args.api_key and not args.config_only:
        parser.error(
            "No bearer token. Either:\n"
            "  1. set API_KEY = \"your_token\" at the top of this file, or\n"
            "  2. $env:INTERCOM_API_KEY = 'your_token'   (PowerShell), or\n"
            "  3. python intercom_to_mintlify.py --api-key your_token"
        )

    root = os.path.abspath(args.root)
    docs_path = args.docs_json or os.path.join(root, "docs.json")
    if not os.path.exists(docs_path):
        sys.stderr.write("ERROR: no docs.json at %s\n" % docs_path)
        return 2

    with open(docs_path, "r", encoding="utf-8") as fh:
        docs = json.load(fh)
    theme_changes = apply_theme(docs)
    nav = docs.setdefault("navigation", {})
    nav, migrated = migrate_to_tabs(nav)

    if args.config_only:
        icons_added = backfill_icons(nav)
        style_status = write_style_css(root, args.dry_run)
        if not args.dry_run:
            with open(docs_path, "w", encoding="utf-8", newline="\n") as fh:
                json.dump(docs, fh, indent=2, ensure_ascii=False)
                fh.write("\n")
        print("")
