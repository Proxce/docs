def mdx_escape(text):
    """MDX parses { } as expressions and < as JSX. Neutralise them in prose."""
    text = text.replace("{", "&#123;").replace("}", "&#125;")
    text = text.replace("<", "&lt;").replace(">", "&gt;")
    return text


def attr_escape(value):
    """Safe for a JSX double-quoted attribute (JSX does not interpolate in strings)."""
    return (str(value or "")
            .replace("&", "&amp;")
            .replace('"', "&quot;")
            .replace("\n", " ")
            .strip())


class HtmlToMdx(HTMLParser):
    """Converts the subset of HTML that Intercom emits into Markdown/MDX."""

    def __init__(self, on_image=None, alt_prefix=""):
        super().__init__(convert_charrefs=True)
        self.on_image = on_image
        self.alt_prefix = alt_prefix
        self.figure_no = 0
        self.blocks = []
        self.stack = [[]]          # buffer stack; text lands in stack[-1]
        # Each open list records the column its markers start at, so a nested
        # list can begin exactly at its parent item's content column. Getting
        # this wrong is what makes steps, screenshots and notes drift apart.
        self.list_stack = []       # [{"tag", "n", "base"}]
        self.li_stack = []         # [{"emitted": bool, "col": int}]
        self.in_pre = False
        self.pre_lang = ""
        self.skip_depth = 0
        # Intercom wraps a standalone image in its own
        # `intercom-interblocks-image` div. Counting those is what tells a
        # screenshot apart from an icon sitting inside a sentence.
        self.image_block = 0
        self.div_image = []
        self.heading = None
        self.blockquote = 0
        self.table = None
        self.row = None
        self.images = []
        self.videos = []
        self.in_link = 0

    # -- buffer helpers ----------------------------------------------------
    def push(self):
        self.stack.append([])

    def pop(self):
        return self.pop_raw().strip()

    def pop_raw(self):
        return "".join(self.stack.pop()) if len(self.stack) > 1 else ""

    def emit(self, text, kind="block"):
        # List items keep their leading indent (nesting) and are joined to their
        # siblings with a single newline, so lists stay tight rather than loose.
        if kind == "li":
            if text.strip():
                self.blocks.append(("li", text.rstrip()))
        elif text and text.strip():
            self.blocks.append(("block", text.strip()))

    def write(self, text):
        self.stack[-1].append(text)

    def flush_block(self, prefix=""):
        text = "".join(self.stack[-1]).strip()
        self.stack[-1] = []
        if text:
            self.emit(prefix + text)

    # -- tags --------------------------------------------------------------
    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag in SKIP_TAGS:
            self.skip_depth += 1
            return
        if self.skip_depth:
            return

        if tag == "div":
            is_image_div = "intercom-interblocks-image" in (a.get("class") or "")
            self.div_image.append(is_image_div)
            if is_image_div:
                self.image_block += 1

        if tag == "br":
            self.write("  \n")
        elif tag == "hr":
            self.flush_block()
            self.emit("---")
        elif tag in ("strong", "b", "em", "i"):
            # buffered so padding can be moved outside the markers on close
            self.push()
        elif tag == "code" and not self.in_pre:
            self.write("`")
        elif tag == "pre":
            self.flush_block()
            self.in_pre = True
            self.pre_lang = ""
            self.push()
        elif tag == "a":
            self.in_link += 1
            self.push()
        elif tag == "img":
            src = a.get("src", "")
            alt = (a.get("alt") or "").strip()
            if src:
                if self.on_image:
                    src = self.on_image(src)
                self.images.append(src)
                # Plain markdown everywhere, never <Frame>. A block component
                # cannot share a step's left edge, and the rounded-border look
                # is restored in style.css instead.
                #
                # A screenshot stands on its own line; an icon sits inside a
                # sentence ("click the [gear] Settings icon") and must stay
                # there, or the sentence is cut in half. Two signals decide:
                # Intercom wraps a standalone image in its own
                # `intercom-interblocks-image` div, and anything else with text
                # already written on the line is mid-sentence.
                inline = self.image_block == 0 and bool(
                    "".join(self.stack[-1]).rstrip("\n").strip())
                if inline:
                    self.write("![%s](%s)" % (self.alt_for(alt), src))
                elif self.li_stack:
                    # own line, so emit_li indents it to the step's content column
                    if "".join(self.stack[-1]).strip():
                        self.write("\n")
                    self.write("![%s](%s)" % (self.alt_for(alt), src))
                else:
                    self.flush_block()
                    self.emit("![%s](%s)" % (self.alt_for(alt), src))
        elif tag == "iframe":
            src = a.get("src", "")
            if src:
                self.flush_block()
                self.videos.append(src)
                self.emit(self.frame_video(src, a.get("title") or ""))
            self.skip_depth += 1  # swallow any fallback content inside the iframe
        elif tag in ("h1", "h2", "h3", "h4", "h5", "h6"):
            self.flush_block()
            self.heading = int(tag[1])
            self.push()
        elif tag == "blockquote":
            self.flush_block()
            self.blockquote += 1
        elif tag in ("ul", "ol"):
            # A nested list inside <li>: emit the parent step first, then start
            # the child list at that step's content column.
            if self.li_stack and not self.li_stack[-1]["emitted"]:
                text = self.pop()
                self.li_stack[-1]["col"] = self.emit_li(text)
                self.li_stack[-1]["emitted"] = True
                self.push()
            else:
                self.flush_block()
            base = self.li_stack[-1]["col"] if self.li_stack else 0
            self.list_stack.append({"tag": tag, "n": 0, "base": base})
        elif tag == "li":
            self.push()
            base = self.list_stack[-1]["base"] if self.list_stack else 0
            self.li_stack.append({"emitted": False, "col": base + 3})
        elif tag == "table":
            self.flush_block()
            self.table = []
        elif tag == "tr":
            self.row = []
        elif tag in ("td", "th"):
            self.push()
        elif tag in BLOCK_TAGS:
            # Intercom nests <p> inside <li>. Flushing there would drop the bullet
            # and turn every step into a loose paragraph, so keep it in the item.
            if self.li_stack:
                if "".join(self.stack[-1]).strip():
                    self.write("\n")
            else:
                self.flush_block()

    def alt_for(self, alt):
        """Intercom screenshots almost never carry alt text, so a positional
        fallback is generated rather than shipping an empty alt attribute."""
        alt = re.sub(r"\s+", " ", (alt or "")).replace("]", "").strip()
        if alt:
            return alt
        self.figure_no += 1
        return "%s - screenshot %d" % (self.alt_prefix or "Screenshot", self.figure_no)

    @staticmethod
    def frame_video(src, title):
        title_a = attr_escape(title)
        title_attr = '\n    title="%s"' % title_a if title_a else ""
        return ('<Frame>\n  <iframe\n    className="w-full aspect-video rounded-xl"\n'
                '    src="%s"%s\n    allowFullScreen\n  />\n</Frame>'
                % (attr_escape(src), title_attr))

    def emit_li(self, text):
        """Emit one list item and return the column its content starts at.

        CommonMark measures nesting from the content column, not from a fixed
        two spaces: under `1. ` that is column 3, under `- ` column 2, and under
        `10. ` column 4. Indenting to a fixed width is why screenshots and
        sub-steps used to hang off the left edge of the step they belong to.
        """
        if not self.list_stack:
            self.emit(text)
            return 0
        lst = self.list_stack[-1]
        base = lst["base"]
        if lst["tag"] == "ol":
            lst["n"] += 1
            marker = "%d. " % lst["n"]
        else:
            marker = "- "
        col = base + len(marker)
        lines = [l.strip() for l in text.splitlines() if l.strip()]
        if not lines:
            # no text before a nested list: skip the empty bullet, but keep the
            # column so the child list still indents correctly
            return col
        body = ("\n" + " " * col).join(lines)
        self.emit(" " * base + marker + body, kind="li")
        return col

    def emit_li_continuation(self, text, col):
        """Prose that follows a nested list but still belongs to the parent step."""
        lines = [l.strip() for l in text.splitlines() if l.strip()]
        if lines:
            self.emit(" " * col + ("\n" + " " * col).join(lines), kind="li")

    def handle_endtag(self, tag):
        # iframe must be checked before the skip guard: its own start tag raised
        # skip_depth, so the guard would otherwise never let it be lowered again.
        if tag in SKIP_TAGS or tag == "iframe":
            self.skip_depth = max(0, self.skip_depth - 1)
            return
        if self.skip_depth:
            return

        if tag == "div" and self.div_image:
            if self.div_image.pop():
                self.image_block = max(0, self.image_block - 1)

        if tag in ("strong", "b", "em", "i"):
            # "**Bold **next" never closes in Markdown. Keep the padding, but put
            # it outside the emphasis markers where it renders correctly.
            raw = self.pop_raw()
            inner = raw.strip()
            if inner:
                marker = "**" if tag in ("strong", "b") else "*"
                lead = raw[:len(raw) - len(raw.lstrip())]
                trail = raw[len(raw.rstrip()):]
                self.write("%s%s%s%s%s" % (lead, marker, inner, marker, trail))
            elif raw:
                self.write(raw)
        elif tag == "code" and not self.in_pre:
            self.write("`")
        elif tag == "pre":
            code = self.pop()
            self.in_pre = False
            self.emit("```%s\n%s\n```" % (self.pre_lang, code))
        elif tag == "a":
            self.in_link = max(0, self.in_link - 1)
            text = self.pop()
            href = getattr(self, "_href", "") or ""
            # Intercom wraps screenshots in a lightbox <a> pointing at the same
            # image. Unwrap those to a Frame instead of emitting a linked image.
            bare = re.fullmatch(r"!\[([^\]]*)\]\(([^)\s]+)\)", text.strip())
            if bare:
                # the image was already written by handle_starttag("img"); the
                # surrounding lightbox <a> adds nothing, so keep just the image
                self.write(text.strip())
            elif text and href:
                self.write("[%s](%s)" % (text, href))
            elif text:
                self.write(text)
            self._href = ""
        elif tag in ("h1", "h2", "h3", "h4", "h5", "h6"):
            text = self.pop()
            if text:
                self.emit("#" * (self.heading or 2) + " " + text)
            self.heading = None
        elif tag == "blockquote":
            text = "".join(self.stack[-1]).strip()
            self.stack[-1] = []
            if text:
                self.emit("\n".join("> " + l for l in text.splitlines()))
            self.blockquote = max(0, self.blockquote - 1)
        elif tag in ("ul", "ol"):
            if self.list_stack:
                self.list_stack.pop()
        elif tag == "li":
            text = self.pop()
            entry = self.li_stack.pop() if self.li_stack else {"emitted": True, "col": 0}
            if not entry["emitted"]:
                self.emit_li(text)
            elif text:
                # Intercom puts the outcome sentence ("The pop-up box is
                # displayed.") after the sub-steps. It used to be dropped here.
                self.emit_li_continuation(text, entry["col"])
        elif tag in ("td", "th"):
            if self.row is not None:
                self.row.append(self.pop().replace("|", "\\|").replace("\n", " "))
            else:
                self.pop()
        elif tag == "tr":
            if self.table is not None and self.row:
                self.table.append(self.row)
            self.row = None
        elif tag == "table":
            self.emit_table()
        elif tag in BLOCK_TAGS:
            if self.li_stack:
                if "".join(self.stack[-1]).strip():
                    self.write("\n")
            else:
                self.flush_block()

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag not in ("br", "hr", "img"):
            self.handle_endtag(tag)

    def emit_table(self):
        rows = [r for r in (self.table or []) if any(c.strip() for c in r)]
        self.table = None
        if not rows:
            return
        width = max(len(r) for r in rows)
        rows = [r + [""] * (width - len(r)) for r in rows]
        head, body = rows[0], rows[1:]
        lines = ["| " + " | ".join(head) + " |",
                 "| " + " | ".join(["---"] * width) + " |"]
        for r in body:
            lines.append("| " + " | ".join(r) + " |")
        self.emit("\n".join(lines))

    def handle_data(self, data):
        if self.skip_depth:
            return
        if self.in_pre:
            self.write(data)
            return
        text = re.sub(r"\s+", " ", data)
        if text.strip() or (text == " " and self.stack[-1]):
            self.write(mdx_escape(text))

    # links need the href captured at start time
    def handle_starttag_a(self, attrs):
        pass

    def close(self):
        super().close()
        self.flush_block()
        out = []
        for kind, text in self.blocks:
            if not text.strip():
                continue
            # consecutive list items stay in one tight block
            if kind == "li" and out and out[-1][0] == "li":
                out[-1] = ("li", out[-1][1] + "\n" + text)
            else:
                out.append((kind, text))
        return "\n\n".join(text for _, text in out)


def html_to_mdx(body_html, on_image=None, alt_prefix=""):
    """Convert an Intercom article body to MDX text."""
    if not body_html:
        return "", [], []

    parser = HtmlToMdx(on_image=on_image, alt_prefix=alt_prefix)

    # capture <a href> since HTMLParser gives attrs only at start
    original = parser.handle_starttag

    def patched(tag, attrs):
        if tag == "a":
            parser._href = dict(attrs).get("href", "")
        original(tag, attrs)

    parser.handle_starttag = patched
    parser.feed(body_html)
    text = parser.close()

    text = re.sub(r"\n{3,}", "\n\n", text)
    text = re.sub(r"[ \t]+\n", "\n", text)
    return text.strip(), parser.images, parser.videos


# --------------------------------------------------------------------------
# Document template
# --------------------------------------------------------------------------
#  Every page is forced into one shape, whatever the Intercom source looked
#  like:
#
#      title / description / keywords    <- frontmatter, the page's only H1
#      ## Introduction
#      ## Prerequisites
#      ## Steps to <do the task>
#      ###   sub-procedure
#      ####    sub-sub-procedure
#      ## Additional Information          (optional)
#      ## Related Articles                (optional)
#
#  The body never contains an H1. Intercom writes its top-level sections as
#  <h1>, which rendered alongside the frontmatter title as a second 32px
#  heading - the reason pages read as oversized.
# --------------------------------------------------------------------------

# Canonical spelling for the sections the template defines. A source heading
# whose text matches a key (case-insensitively) is renamed and pinned to H2.
SECTION_ALIASES = {
    "introduction": "Introduction",
    "intro": "Introduction",
    "overview": "Introduction",
    "purpose": "Introduction",
    "prerequisite": "Prerequisites",
    "prerequisites": "Prerequisites",
    "pre-requisite": "Prerequisites",
    "pre-requisites": "Prerequisites",
    "pre requisites": "Prerequisites",
    "requirement": "Prerequisites",
    "requirements": "Prerequisites",
    "additional information": "Additional Information",
    "additional info": "Additional Information",
    "misc": "Additional Information",
    "miscellaneous": "Additional Information",
    "related article": "Related Articles",
    "related articles": "Related Articles",
    "related links": "Related Articles",
    "see also": "Related Articles",
}

# Order the template expects, used only for the audit report.
TEMPLATE_SECTIONS = ["Introduction", "Prerequisites", "Steps",
                     "Additional Information", "Related Articles"]
OPTIONAL_SECTIONS = {"Additional Information", "Related Articles"}

HEADING_RE = re.compile(r"^(#{1,6})[ \t]+(.*?)[ \t]*$")
FENCE_RE = re.compile(r"^[ \t]*(```+|~~~+)")

# "Note", "Note:", "**Note:**", "**Note**:" - Intercom uses all of them.
NOTE_LABELS = "Note|Notes|Important|Caution|Warning|Tip|Recommended|Remember"
NOTE_RE = re.compile(
    r"^(?P<indent>[ \t]*)"
    r"(?:\*\*(?P<a>" + NOTE_LABELS + r")[ \t]*:?[ \t]*\*\*[ \t]*:?"
    r"|(?P<b>" + NOTE_LABELS + r")[ \t]*:)"
    r"[ \t]*(?P<body>.*)$",
    re.I,
)
CALLOUT_FOR = {
    "note": "Note", "notes": "Note", "remember": "Note",
    "tip": "Tip", "recommended": "Tip",
    "important": "Warning", "caution": "Warning", "warning": "Warning",
}

# The visible label kept inside the callout. Mintlify draws an icon but no
# word, and oloid.help writes the word out, so it is preserved here: "Note:"
# for information, and each other kind keeps the term the author used, which
# says more than the component name does ("Important:" over "Warning:").
CALLOUT_LABEL = {
    "note": "Note", "notes": "Note", "remember": "Remember",
    "tip": "Tip", "recommended": "Recommended",
    "important": "Important", "caution": "Caution", "warning": "Warning",
}

# An already-converted callout must not be wrapped again on a second run.
CALLOUT_OPEN_RE = re.compile(r"^[ \t]*<(Note|Warning|Tip|Info|Check|Danger)\b")
CALLOUT_CLOSE_RE = re.compile(r"^[ \t]*</(Note|Warning|Tip|Info|Check|Danger)>")

KEYWORDS_TAIL_RE = re.compile(
    r"\n+(?:-{3,}[ \t]*\n+)?#{1,6}[ \t]*\*{0,2}[ \t]*Keywords?[ \t]*\*{0,2}[ \t]*:?[ \t]*\n"
    r"(?P<tail>.*)\Z",
    re.S | re.I,
)


def split_fences(body):
    """Yield (line, inside_code_fence) so transforms never touch code blocks."""
    fence = None
    for line in body.splitlines():
        m = FENCE_RE.match(line)
        if fence is None:
            if m:
                fence = m.group(1)[0]
                yield line, True
            else:
                yield line, False
        else:
            yield line, True
            if m and m.group(1)[0] == fence:
                fence = None


def anchor_slug(text):
    """Approximate Mintlify's heading anchors: lowercase, punctuation dropped."""
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text or "")
    text = re.sub(r"[*`_]+", "", text)
    text = re.sub(r"&\w+;|&#\d+;", " ", text)
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def clean_heading_text(text):
    """Headings arrive as '**Introduction**' or 'Configure Theme tab:'."""
    text = text.strip()
    text = re.sub(r"^\*{1,3}(.*?)\*{1,3}$", r"\1", text).strip()
    text = re.sub(r"[ \t]*[:：]$", "", text).strip()
    # "Configure Theme tab" and "Configure Details Tab" in one document
    text = re.sub(r"\btab\b\s*$", "Tab", text)
    text = re.sub(r"\btabs\b\s*$", "Tabs", text)
    return re.sub(r"\s+", " ", text)


def extract_keywords(body):
    """Pull the trailing Keywords block out of the body into frontmatter.

    Intercom stores them as a one-row pipe table, which markdown renders as a
    malformed header-only table - a stray box at the foot of every page.
    """
    m = KEYWORDS_TAIL_RE.search(body)
    if not m:
        return body, []

    words = []
    for line in m.group("tail").splitlines():
        line = line.strip()
        if not line or re.fullmatch(r"-{3,}", line) or line.startswith("#"):
            continue
        cells = line.strip("|").split("|") if line.startswith("|") else re.split(r"[,;]", line)
        for cell in cells:
            cell = re.sub(r"[*`]", "", cell).strip()
            if cell and not re.fullmatch(r"[-: ]+", cell):
                words.append(re.sub(r"\s+", " ", cell))

    seen, out = set(), []
    for word in words:
        if word.lower() not in seen:
            seen.add(word.lower())
            out.append(word)
    return body[:m.start()].rstrip(), out


def normalize_headings(body, mirror=False):
    """Strip bold from headings and shift the document so its shallowest
    heading is H2 - never H1, which would render a second 32px title under the
    frontmatter one.

    `mirror=True` is the oloid.help-faithful mode: headings keep their own text
    and their own relative depth. Nothing is renamed to a template section and
    nothing is promoted, so the page reads exactly as the help centre does.
    """
    levels = [len(m.group(1)) for line, fenced in split_fences(body)
              if not fenced for m in [HEADING_RE.match(line)] if m]
    shift = (2 - min(levels)) if levels else 0

    out = []
    for line, fenced in split_fences(body):
        m = HEADING_RE.match(line) if not fenced else None
        if not m:
            out.append(line)
            continue
        level, text = len(m.group(1)), clean_heading_text(m.group(2))
        if not text:
            continue
        canonical = None if mirror else SECTION_ALIASES.get(text.lower())
        if canonical:
            # a template section is always top level, whatever Intercom used
            text, level = canonical, 2
        elif not mirror and re.match(r"^steps?\b|^how to\b|^procedure\b", text, re.I):
            level = 2
        else:
            level = min(6, max(2, level + shift))
        out.append("#" * level + " " + text)
    return "\n".join(out)


LIST_ITEM_RE = re.compile(r"^(?P<indent>[ \t]*)(?P<marker>[-*+]|\d+[.)])[ \t]+(?P<text>.*)$")


def frames_to_images(body):
    """Unwrap <Frame><img/></Frame> back to plain markdown.

    A Frame is a block component and cannot share a step's left edge, so a
    screenshot inside a procedure drifts back to the margin. Plain images
    indent with their step; style.css restores the rounded border.
    Video frames (<Frame><iframe/></Frame>) are left alone.
    """
    def repl(match):
        block = match.group(0)
        src = re.search(r'src="([^"]*)"', block)
        if not src:
            return block
        alt = re.search(r'alt="([^"]*)"', block)
        caption = re.search(r'caption="([^"]*)"', block)
        label = (alt.group(1) if alt else "") or (caption.group(1) if caption else "")
        label = html.unescape(label).replace("]", "").strip()
        return "![%s](%s)" % (label, html.unescape(src.group(1)))

    return re.sub(r"<Frame\b[^>]*>\s*<img\b[^>]*/>\s*</Frame>", repl, body, flags=re.S)


def reindent_lists(body):
    """Re-indent every list to its parent's content column.

    CommonMark nests from the content column: under `1. ` that is column 3, and
    under `- ` column 2. Content indented a flat two spaces under `1. ` is one
    column short, so sub-steps, screenshots and outcome sentences break out of
    the step they belong to. This recomputes the columns from the source
    structure and is safe to run over an already-correct document.
    """
    out, stack = [], []
    jsx = None          # a callout already in the file moves as one block
    for line, fenced in split_fences(body):
        if fenced:
            out.append(line)
            continue
        raw = line.replace("\t", "    ")
        stripped = raw.strip()
        if not stripped:
            out.append("")
            continue

        indent = len(raw) - len(raw.lstrip(" "))

        # Inside a JSX block, shift every line by the same amount instead of
        # re-indenting each one, or the component's inner lines collapse onto
        # its opening tag and any bullets inside it get treated as steps.
        if jsx is not None:
            out.append(" " * max(0, indent + jsx["delta"]) + stripped)
            if stripped.startswith("</" + jsx["tag"]) and indent <= jsx["src"]:
                jsx = None
            continue

        # An opening JSX tag starts a protected block, at any indent. Checked
        # before the list and top-level branches so that a callout sitting at
        # the margin still shields the bullets written inside it.
        open_tag = re.match(r"<([A-Z][A-Za-z0-9]*)\b", stripped)
        if open_tag and not stripped.endswith("/>") \
                and not stripped.endswith("</%s>" % open_tag.group(1)):
            if indent == 0 or not stack:
                target = indent if stack else 0
            else:
                target = stack[-1]["content"]
            jsx = {"tag": open_tag.group(1), "src": indent, "delta": target - indent}
            out.append(" " * target + stripped)
            continue

        match = LIST_ITEM_RE.match(raw)
        if match:
            # a sibling may be indented a space out; only a clear step in
            # indentation opens or closes a level
            while len(stack) > 1 and indent < stack[-1]["src"] - 1:
                stack.pop()
            if not stack:
                stack.append({"src": indent, "base": 0, "content": 0})
            elif indent >= stack[-1]["src"] + 2:
                stack.append({"src": indent, "base": stack[-1]["content"], "content": 0})
            elif indent < stack[-1]["src"] - 1:
                # Only the outermost level is left and this item sits further
                # left than the one that opened the list - Intercom does this
                # when a list starts indented and later items do not. Re-base
                # the level; popping it would empty the stack and the next
                # line would crash on stack[-1].
                stack[-1] = {"src": indent, "base": 0, "content": 0}

            level = stack[-1]
            marker = match.group("marker")
            marker = (marker + " ") if marker[-1] in ".)" else "- "
            level["content"] = level["base"] + len(marker)
            out.append(" " * level["base"] + marker + match.group("text").rstrip())
            continue

        if HEADING_RE.match(raw) or indent == 0:
            stack = []
            out.append(stripped)
            continue

        # indented prose or screenshot: it continues the current step
        out.append((" " * stack[-1]["content"] + stripped) if stack else raw.rstrip())
    return "\n".join(out)


def notes_to_callouts(body):
    """Turn '**Note:** ...' into <Note>/<Warning>/<Tip>, at the right indent.

    The label is kept as the first thing inside the callout ("**Note:**",
    "**Important:**"), because Mintlify draws an icon but never the word.

    A note inside a numbered step is indented to that step's content column, so
    the callout lines up with the step text instead of resetting to the margin.
    """
    lines = list(split_fences(body))
    out, i, in_callout = [], 0, 0
    while i < len(lines):
        line, fenced = lines[i]

        # never re-wrap a callout this function produced on an earlier run
        if not fenced and CALLOUT_OPEN_RE.match(line):
            in_callout += 1
        elif not fenced and CALLOUT_CLOSE_RE.match(line):
            in_callout = max(0, in_callout - 1)

        m = NOTE_RE.match(line) if (not fenced and not in_callout) else None
        if not m:
            out.append(line)
            i += 1
            continue

        label = (m.group("a") or m.group("b") or "note").lower()
        indent = m.group("indent").replace("\t", "    ")
        content = [m.group("body").strip()] if m.group("body").strip() else []
        i += 1

        # "**Note:**" on its own line introduces the bullet list beneath it
        if not content:
            while i < len(lines) and not lines[i][0].strip():
                i += 1
            while i < len(lines) and lines[i][0].strip() and not lines[i][1]:
                nxt = lines[i][0]
                if HEADING_RE.match(nxt) or NOTE_RE.match(nxt):
                    break
                content.append(nxt.rstrip())
                i += 1
            base = min((len(l) - len(l.lstrip()) for l in content if l.strip()), default=0)
            content = [l[base:] if len(l) > base else l.strip() for l in content]

        if not content:
            continue

        component = CALLOUT_FOR.get(label, "Note")
        tag = "**%s:**" % CALLOUT_LABEL.get(label, label.title())

        # A single sentence reads best with the label inline; a bullet list
        # needs the label on its own line or the first bullet swallows it.
        first = content[0].lstrip()
        if len(content) == 1 and not first.startswith(("-", "*", "+")):
            content = ["%s %s" % (tag, first)]
        else:
            content = [tag, ""] + content

        if out and out[-1].strip():
            out.append("")
        out.append(indent + "<" + component + ">")
        out.extend(indent + "  " + l if l.strip() else "" for l in content)
        out.append(indent + "</" + component + ">")
        if i < len(lines) and lines[i][0].strip():
            out.append("")
    return "\n".join(out)


COMPONENT_LABEL = {"Note": "Note", "Info": "Note", "Tip": "Tip",
                   "Warning": "Warning", "Check": "Check", "Danger": "Danger"}
LABELLED_RE = re.compile(r"^[ \t]*\*\*[A-Za-z][A-Za-z ]*:\*\*")


def label_existing_callouts(body):
    """Backfill the label on callouts written before labels were kept.

    Only the component name is available for those, so <Note> becomes
    "**Note:**". Idempotent: a callout whose first line is already a bold
    label is left untouched.
    """
    lines = body.splitlines()
    out, i = [], 0
    while i < len(lines):
        line = lines[i]
        out.append(line)
        m = CALLOUT_OPEN_RE.match(line)
        if not m or line.rstrip().endswith("/>"):
            i += 1
            continue

        i += 1
        # find the first line with content inside this callout
        blanks = []
        while i < len(lines) and not lines[i].strip():
            blanks.append(lines[i])
            i += 1
        if i >= len(lines) or CALLOUT_CLOSE_RE.match(lines[i]):
            out.extend(blanks)
            continue

        out.extend(blanks)
        first = lines[i]
        if LABELLED_RE.match(first):
            out.append(first)
            i += 1
            continue

        tag = "**%s:**" % COMPONENT_LABEL.get(m.group(1), m.group(1))
        indent = first[:len(first) - len(first.lstrip())]
        stripped = first.strip()
        if stripped.startswith(("-", "*", "+")):
            out += [indent + tag, "", first]
        else:
            out.append(indent + tag + " " + stripped)
        i += 1
    return "\n".join(out)


def fix_anchor_links(body):
    """Rewrite Intercom's '#h_e6d165b891' anchors, which 404 in Mintlify.

    The link text usually names the heading it points at, so it is matched
    against the document's own headings. An unmatched link loses its href
    rather than shipping a dead one.
    """
    slugs = [anchor_slug(m.group(2))
             for line, fenced in split_fences(body) if not fenced
             for m in [HEADING_RE.match(line)] if m]
    slugs = [s for s in slugs if s]

    def resolve(match):
        text = match.group(1)
        want = anchor_slug(text)
        if not want:
            return text
        for slug in slugs:
            if slug == want:
                return "[%s](#%s)" % (text, slug)
        for slug in slugs:
            if want in slug or slug in want:
                return "[%s](#%s)" % (text, slug)
        return text

    return re.sub(r"\[([^\]\n]+)\]\(#h_[0-9a-zA-Z_]+\)", resolve, body)


def is_bogus_url(href):
    """True when a link's target is prose that ended up in Intercom's URL box.

    Authors sometimes type a description where the URL goes; Intercom stores it
    verbatim with an https:// bolted on, producing hrefs like
    "https://Landing page for the user-portal. Displays all the ...".

    Only the authority is examined, never the rest of the URL. Percent-encoded
    spaces are perfectly legal in a path or a fragment - Intercom's own deep
    links use `#:~:text=Facility%20Code` - and treating those as broken would
    destroy working links.
    """
    match = re.match(r"^https?://([^/?#]*)", href or "", re.I)
    if not match:
        return False
    host = match.group(1)
    if not host:
        return True
    if "%20" in host or " " in host:          # a hostname cannot contain a space
        return True
    host = host.split("@")[-1].split(":")[0]  # drop userinfo and port
    if "." not in host.rstrip("."):           # no dot means no TLD
        return True
    return False


def tidy_links(body):
    """Drop the help-centre suffix from link text, and unlink bogus targets."""
    def fix(match):
        text, href = match.group(1), match.group(2)
        text = re.sub(r"\s*\|\s*Oloid Help Cent(?:er|re)\s*$", "", text, flags=re.I)
        text = text.strip() or match.group(1).strip()
        if is_bogus_url(href):
            # keep what the author wrote, lose the link that would 404
            return text
        return "[%s](%s)" % (text, href)
    return re.sub(r"\[([^\]\n]+)\]\((https?://[^)\s]+)\)", fix, body)


def tidy_entities(body):
    """'Directory &gt; People' reads as source noise; '>' is safe mid-line.

    It is left alone at the start of a line, where markdown would read it as a
    blockquote, and '&lt;' is left escaped because MDX parses '<' as JSX.
    """
    out = []
    for line, fenced in split_fences(body):
        if not fenced:
            # Intercom sprinkles zero-width spaces through pasted content; each
            # one survives as a line of its own and renders as a blank paragraph
            line = line.replace("​", "").replace("‌", "").replace("﻿", "")
            line = line.replace(" ", " ")
            if not line.lstrip().startswith("&gt;"):
                line = line.replace("&gt;", ">")
            # "**OKTA** **ID**" is two runs of bold with a space between
            line = re.sub(r"\*\*([^*\n]+?)\*\* \*\*([^*\n]+?)\*\*", r"**\1 \2**", line)
        out.append(line)
    return "\n".join(out)


def tidy_blank_lines(body):
    out, blanks = [], 0
    for line, fenced in split_fences(body):
        line = line.rstrip() if not fenced else line
        if not fenced and not line.strip():
            blanks += 1
            if blanks > 1:
                continue
        else:
            blanks = 0
        out.append(line)
    return "\n".join(out).strip()


def audit_sections(body):
    """Report which template sections the page has, without inventing any."""
    found = set()
    for line, fenced in split_fences(body):
        m = HEADING_RE.match(line) if not fenced else None
        if not m or len(m.group(1)) != 2:
            continue
        text = m.group(2).strip()
        if text in TEMPLATE_SECTIONS:
            found.add(text)
        elif re.match(r"^steps?\b|^how to\b|^procedure\b", text, re.I):
            found.add("Steps")
    missing = [s for s in TEMPLATE_SECTIONS
               if s not in found and s not in OPTIONAL_SECTIONS]
    return {"found": [s for s in TEMPLATE_SECTIONS if s in found], "missing": missing}


def apply_template(body, mirror=False):
    """Normalise one converted article. Returns (body, keywords, audit).

    Everything here is mechanical - entity cleanup, list columns, callouts,
    dead anchors - and applies in both modes. Only heading rewriting differs:
    with `mirror=True` the article keeps oloid.help's own section structure,
    and the audit becomes a report of what is there rather than a checklist of
    what a template demands.
    """
    body, keywords = extract_keywords(body or "")
    body = normalize_headings(body, mirror=mirror)
    body = frames_to_images(body)
    body = tidy_entities(body)
    body = tidy_links(body)
    # columns must be correct before callouts are placed, because a callout is
    # indented to the column of the step it belongs to
    body = reindent_lists(body)
    body = notes_to_callouts(body)
    body = label_existing_callouts(body)
    body = fix_anchor_links(body)
    body = tidy_blank_lines(body)
    return body, keywords, audit_sections(body)


