def download_image(url, root, article_id, dry_run, stats):
    """Save a remote image locally and return the docs-absolute path.

    Intercom serves images from signed CDN URLs whose ?expires= is only hours
    away, so the signature is stripped and the bytes are stored in the repo.
    Files are namespaced per article to avoid collisions between articles that
    happen to use the same original filename.
    """
    clean = url.split("?")[0]
    parsed = urllib.parse.urlparse(clean)
    name = urllib.parse.unquote(os.path.basename(parsed.path)) or "image"
    name = re.sub(r"[^A-Za-z0-9._-]+", "-", name).strip("-.") or "image"
    stem, dot, ext = name.rpartition(".")
    if not dot:
        stem, ext = name, "png"

    # Intercom names almost every screenshot "image.png", so the basename alone
    # collides and articles end up sharing one file. The URL digest keeps each
    # distinct image separate while staying stable across re-runs.
    digest = hashlib.sha1(clean.encode("utf-8")).hexdigest()[:8]
    name = "%s-%s.%s" % (stem[:48], digest, ext.lower())

    rel = "/%s/%s/%s" % (IMAGE_DIR.strip("/"), article_id, name)
    dest = os.path.join(root, IMAGE_DIR, str(article_id), name)

    if dry_run:
        return rel
    if os.path.exists(dest):
        stats["reused"] += 1
        stats["bytes"] += os.path.getsize(dest)
        return rel
    try:
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        req = urllib.request.Request(clean, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(req, timeout=60) as resp:
            data = resp.read()
        with open(dest, "wb") as fh:
            fh.write(data)
        stats["saved"] += 1
        stats["bytes"] += len(data)
        if len(data) > MAX_IMAGE_BYTES:
            stats["oversize"].append((rel, len(data)))
        elif len(data) > 5 * 1024 * 1024:
            stats["large"].append((rel, len(data)))
        return rel
    except Exception as exc:  # noqa: BLE001 - an image is never worth aborting for
        sys.stderr.write("  ! image failed (%s), keeping remote URL\n" % exc)
        stats["failed"].append({"article": str(article_id), "url": url, "error": str(exc)})
        return url


# --------------------------------------------------------------------------
# Navigation-driven migration
# --------------------------------------------------------------------------
#  navigation.json owns the tree: every group lists the Intercom collections
#  ("Product :: Collection") whose articles belong in it. This mode fetches
#  every article, resolves its collection, and writes the page into that
#  group's directory. docs.json is not touched here - build_nav.py rebuilds it
#  from whatever .mdx files end up on disk.
#
#  Three GET endpoints, and nothing else:
#      GET /help_center/collections   the Product / Section tree
#      GET /articles                  every article summary, 150 per page
#      GET /articles/{id}             the full body
#  This script never calls POST, PUT or DELETE against Intercom.
# --------------------------------------------------------------------------

NAV_FILE = "navigation.json"
PLACEHOLDER_MARK = "This section is a placeholder."


def _helpers():
    """intercom_fetch.py owns the HTTP and pagination layer, build_nav.py owns
    the tree walk. Import both rather than keeping a second copy of either."""
    import build_nav
    import intercom_fetch
    return build_nav, intercom_fetch


def nav_group_dirs(nav, build_nav):
    """{normalised 'Product :: Collection': [group directory, ...]}

    A collection can be listed in more than one group - Healthcare appears
    under Windows > Version 1 and again under Resources > Industries. The first
    directory owns the file on disk; the second group picks the same pages up
    through its `pages_from` key, so the article exists once and is listed
    twice.
    """
    mapping = {}
    for grp, slug_parts, _crumbs in build_nav.iter_groups(nav):
        directory = "/".join(slug_parts) if slug_parts else "."
        for coll in grp.get("collections") or []:
            mapping.setdefault(build_nav.norm(coll), []).append(directory)
    return mapping


def drop_repeated_title(body, title):
    """Drop a leading heading that just restates the article title.

    Intercom keeps the title out of `body`, but a few articles open with it
    anyway. The frontmatter title already renders as the page's H1, and
    oloid.help never shows it twice.
    """
    lines = (body or "").lstrip("\n").splitlines()
    if not lines:
        return body
    m = HEADING_RE.match(lines[0])
    if not m:
        return body
    squash = lambda s: re.sub(r"[^a-z0-9]+", "", (s or "").lower())
    if squash(clean_heading_text(m.group(2))) != squash(title):
        return body
    return "\n".join(lines[1:]).lstrip("\n")


#: Words of prose, besides the video, a page may carry and still be a video.
VIDEO_ONLY_WORDS = 40


def is_video_only(body_mdx):
    """A page that is just a video: an embed plus at most a one-line intro.

    Articles that embed a video among real steps are not video pages and
    stay in their own group.
    """
    if not re.search(r"<(iframe|video)\b", body_mdx or ""):
        return False
    text = re.sub(r"\{/\*.*?\*/\}", "", body_mdx, flags=re.S)
    text = re.sub(r"<Frame>.*?</Frame>", "", text, flags=re.S)
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", text)
    text = re.sub(r"<[^>]+>", "", text)
    return len(re.findall(r"[A-Za-z]{2,}", text)) <= VIDEO_ONLY_WORDS


def drop_placeholder(directory):
    """Remove a group's generated overview once real articles have landed."""
    path = os.path.join(directory, "overview.mdx")
    if not os.path.exists(path):
        return False
    with open(path, "r", encoding="utf-8") as fh:
        if PLACEHOLDER_MARK not in fh.read():
            return False          # somebody wrote a real overview; keep it
    os.remove(path)
    return True


# --------------------------------------------------------------------------
# Placement: collections first, title rules before them
# --------------------------------------------------------------------------
#  Most articles are placed by their Intercom collection. Where the new
#  navigation has no collection to draw on - Zebra, Linux & Thin Clients,
#  the Vaults, Time Clock, everything in _Unassigned - a group's `match`
#  places articles by title instead:
#
#      "match": {"titles": ["(?i)\\bzebra\\b"], "from": ["*"]}
#
#  `titles` are regexes. They are tried against articles from _Unassigned,
#  plus the collections named in `from` ("*" for any), before the collection
#  mapping. Rules are tried in navigation.json order with children before
#  their parent, so "Windows Login V2" wins over "Windows Login" and the
#  product groups win over the generic portal groups below them. Every title
#  placement is listed in the report, so a wrong guess is easy to spot.
# --------------------------------------------------------------------------

def build_rules(nav, build_nav):
    import intercom_fetch
    unassigned = build_nav.norm("%s :: %s" % (intercom_fetch.UNASSIGNED,
                                              intercom_fetch.UNASSIGNED))
    rules = []

    def walk(node, parts, crumbs):
        for grp in node.get("groups") or []:
            p = parts + ([grp["slug"]] if grp.get("slug") else [])
            c = crumbs + [grp.get("group")]
            walk(grp, p, c)                     # children first
            match = grp.get("match") or {}
            scope = match.get("from") or []
            keys = {build_nav.norm(s) for s in scope if s != "*"} | {unassigned}
            for pattern in match.get("titles") or []:
                rules.append({"rx": re.compile(pattern), "any": "*" in scope,
                              "keys": keys, "dir": "/".join(p), "crumbs": c})

    for tab in nav.get("tabs") or []:
        tab_parts = [tab["slug"]] if tab.get("slug") else []
        walk(tab, tab_parts, [tab.get("tab")])
        for item in tab.get("menu") or []:
            walk(item, tab_parts + ([item["slug"]] if item.get("slug") else []),
                 [tab.get("tab"), item.get("item")])
    return rules


def excluded_keys(nav, build_nav):
    """Collections kept out of the main navigation (M-Tag, Oloid App, ...)."""
    return {build_nav.norm(c) for c in nav.get("excluded_collections") or []}


def unmapped_directory(nav, build_nav):
    """The group flagged `catch_unmapped` (Drafts > Unassigned), or None."""
    for grp, parts, _c in build_nav.iter_groups(nav):
        if grp.get("catch_unmapped"):
            return "/".join(parts)
    return None


def place(product, collection, title, mapping, rules, build_nav,
          excluded=frozenset(), unmapped_dir=None):
    """(directory, rule or None, category) for one article.

    category is "excluded" (an excluded collection - collection mapping only,
    never a title rule), "unassigned" (no Intercom collection and no title rule
    matched), "unmapped" (a collection no group claims; filed under
    `unmapped_dir`) or "added" (a home in the main navigation). directory is
    None only for an unmapped article when there is no catch_unmapped group.
    """
    import intercom_fetch
    key = build_nav.norm("%s :: %s" % (product, collection))
    if key in excluded:
        dirs = mapping.get(key)
        return (dirs[0] if dirs else unmapped_dir), None, "excluded"
    for rule in rules:
        if (rule["any"] or key in rule["keys"]) and rule["rx"].search(title or ""):
            return rule["dir"], rule, "added"
    dirs = mapping.get(key)
    if not dirs:
        return unmapped_dir, None, "unmapped"
    unassigned = build_nav.norm("%s :: %s" % (intercom_fetch.UNASSIGNED,
                                              intercom_fetch.UNASSIGNED))
    return dirs[0], None, "unassigned" if key == unassigned else "added"


# --------------------------------------------------------------------------
# Polish: screenshots, icons, alt text, links
# --------------------------------------------------------------------------
#  Runs over the finished .mdx files - at the end of --migrate, or alone with
#  --polish - and is idempotent:
#
#  * A screenshot always stands on its own line, with a blank line before
#    and after, so the step text above it and the outcome sentence below it
#    ("The Tenant Settings screen is displayed.") never render glued to it.
#  * Small images - icons and buttons, judged by their pixel size, or any
#    image sitting mid-sentence whose size is unknown - become
#    <img className="oloid-icon" noZoom>, sized to the text line by style.css.
#  * A generic alt ("... - screenshot 3") is replaced by the step or sentence
#    the image illustrates, else the nearest heading, else the page title.
#  * oloid.help/articles/<id> links point at the page migrated from <id>.
#    Links to articles that were not migrated keep their oloid.help URL and
#    are counted in the report.
# --------------------------------------------------------------------------

IMAGE_MD_RE = re.compile(r"!\[([^\]\n]*)\]\(([^)\s]+)\)")
GENERIC_ALT_RE = re.compile(
    r"^\s*$|screenshot \d+\s*$|^\s*(image|img|screenshot|picture)\s*\d*\s*$"
    r"|^\s*[\w-]+\.(png|jpe?g|gif|webp)\s*$", re.I)
LIST_MARK_RE = re.compile(r"^([ \t]*)((?:\d+[.)]|[-*+])[ \t]+)")
CALLOUT_ANY_CLOSE_RE = re.compile(r"</(Note|Warning|Tip|Info|Check|Danger)>")

#: An image no larger than this on both sides is an icon.
ICON_MAX_SIDE = 100
#: A short, wide image (a button) is treated as an icon too.
BUTTON_MAX_HEIGHT, BUTTON_MAX_WIDTH = 48, 320
#: Longest alt text, in characters.
ALT_MAX = 110


def image_size(path):
    """(width, height) of a PNG, GIF or JPEG on disk, or None."""
    try:
        with open(path, "rb") as fh:
            head = fh.read(65536)
    except OSError:
        return None
    if head[:8] == b"\x89PNG\r\n\x1a\n" and len(head) >= 24:
        return struct.unpack(">II", head[16:24])
    if head[:6] in (b"GIF87a", b"GIF89a"):
        return struct.unpack("<HH", head[6:10])
    if head[:2] == b"\xff\xd8":
        i = 2
        while i + 9 < len(head):
            if head[i] != 0xFF:
                i += 1
                continue
            marker = head[i + 1]
            if marker in (0xC0, 0xC1, 0xC2, 0xC3, 0xC5, 0xC6, 0xC7,
                          0xC9, 0xCA, 0xCB, 0xCD, 0xCE, 0xCF):
                h, w = struct.unpack(">HH", head[i + 5:i + 9])
                return w, h
            if marker in (0xD8, 0x01, 0xFF) or 0xD0 <= marker <= 0xD7:
                i += 2 if marker != 0xFF else 1
                continue
            i += 2 + struct.unpack(">H", head[i + 2:i + 4])[0]
    return None


def is_icon_size(size):
    if not size:
        return False
    w, h = size
    return ((w <= ICON_MAX_SIDE and h <= ICON_MAX_SIDE)
            or (h <= BUTTON_MAX_HEIGHT and w <= BUTTON_MAX_WIDTH))


def plain_text(line):
    """A markdown line reduced to the words a reader sees."""
    t = IMAGE_MD_RE.sub(" ", line)
    t = re.sub(r"\{/\*.*?\*/\}", " ", t)
    t = re.sub(r"<[^>]*>", " ", t)
    t = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", t)
    t = re.sub(r"^\s*(?:#{1,6}|>|\d+[.)]|[-*+])\s+", "", t)
    t = re.sub(r"[*_`]+", "", t).replace("\\", "")
    t = re.sub(r"&#?\w+;", " ", t)
    return re.sub(r"\s+", " ", t).strip()


def alt_text(text):
    text = text.strip().rstrip(":")
    if len(text) > ALT_MAX:
        text = text[:ALT_MAX].rsplit(" ", 1)[0].rstrip(" ,.;:-")
    return text.replace("[", "(").replace("]", ")")


def icon_alt(line, match):
    """'click the [img] **Settings** icon' -> 'Settings icon'."""
    after = re.match(r"\s*\*\*([^*\n]{1,40})\*\*", line[match.end():])
    if after:
        return "%s icon" % after.group(1).strip()
    before = re.search(r"\*\*([^*\n]{1,40})\*\*\s*$", line[:match.start()])
    if before:
        return "%s icon" % before.group(1).strip()
    # "the Oloid app icon [img]" / "the Download button [img] icon"
    words = [w for w in plain_text(line[:match.start()]).split()
             if w.lower().strip(",.;:") not in ("the", "a", "an", "click", "on", "tap",
                                                "select", "then", "and", "or", "your")]
    following = plain_text(line[match.end():]).lower()
    if words and (following.startswith("icon") or words[-1].lower() in ("icon", "button")):
        name = " ".join(words[-3:])
        return name if name.lower().endswith("icon") else name + " icon"
    return "Icon"


def local_image(root, src):
    if not src.startswith("/"):
        return None
    return os.path.join(root, *src.lstrip("/").split("/"))


def polish_images(body, title, root, stats):
    out = []
    state = {"blank": False}            # a screenshot was just emitted
    last_text, last_heading = "", ""
    in_callout = 0
    used_alts = {}

    def emit(text, image=False):
        if image:
            if out and out[-1].strip():
                out.append("")
            out.append(text)
            state["blank"] = True
            return
        if state["blank"] and text.strip() and out and out[-1].strip():
            out.append("")
        if state["blank"] or not text.strip():
            state["blank"] = False
        out.append(text)

    for line, fenced in split_fences(body):
        if fenced:
            emit(line)
            continue
        opens = bool(CALLOUT_OPEN_RE.match(line))
        closes = bool(CALLOUT_ANY_CLOSE_RE.search(line))

        if not IMAGE_MD_RE.search(line):
            heading = HEADING_RE.match(line)
            if heading:
                last_heading, last_text = plain_text(heading.group(2)), ""
            elif not in_callout and not opens:
                words = plain_text(line)
                if len(words) >= 3:
                    last_text = words
            emit(line)
            in_callout = max(0, in_callout + opens - closes)
            continue

        stripped = line.strip()
        mark = LIST_MARK_RE.match(line)
        if mark:
            col = len(mark.group(1)) + len(mark.group(2))
            rest = line[col:].strip()
        else:
            col = len(line) - len(line.lstrip())
            rest = stripped
        standalone = IMAGE_MD_RE.fullmatch(rest) is not None
        table = stripped.startswith("|")
        line_words = plain_text(line)

        def convert(m):
            alt, src = m.group(1), m.group(2)
            size = image_size(local_image(root, src) or "")
            icon = is_icon_size(size) or (size is None and not standalone and not table)
            if icon:
                if GENERIC_ALT_RE.search(alt):
                    alt = icon_alt(line, m)
                stats["icons"] += 1
                return ('<img src="%s" alt="%s" className="oloid-icon" noZoom />'
                        % (attr_escape(src), attr_escape(html.unescape(alt))))
            if GENERIC_ALT_RE.search(alt):
                context = line_words if (line_words and not standalone) else ""
                text = alt_text(context or (last_text if not in_callout else "")
                                or last_heading or title) or "Screenshot"
                used_alts[text] = used_alts.get(text, 0) + 1
                if used_alts[text] > 1:
                    text = "%s (%d)" % (text, used_alts[text])
                alt = mdx_escape(text)
                stats["alts"] += 1
            return "![%s](%s)" % (alt, src)

        new = IMAGE_MD_RE.sub(convert, line)
        if line_words and not standalone:
            last_text = line_words

        if table or not IMAGE_MD_RE.search(new):
            emit(new)                                   # icons only, or a table row
        elif standalone:
            emit(new, image=True)
        else:
            # a full-size screenshot glued into a sentence: give it its own line
            stats["split"] += 1
            pos, first = 0, True
            for m in IMAGE_MD_RE.finditer(new):
                before = new[pos:m.start()]
                if first and not before.strip():
                    emit(before + m.group(0), image=True)   # "1. ![..]" keeps its marker
                else:
                    if before.strip():
                        emit(before.rstrip() if first else " " * col + before.strip())
                    emit(" " * col + m.group(0), image=True)
                pos, first = m.end(), False
            after = new[pos:]
            if after.strip():
                emit(" " * col + after.strip())
        in_callout = max(0, in_callout + opens - closes)

    return "\n".join(out)


SOURCE_RE = re.compile(r"\{/\* Source: Intercom article (\d+)")
ARTICLE_URL_RE = re.compile(
    r"https?://(?:www\.)?(?:oloid\.help|intercom\.help/oloid)/"
    r"(?:[a-z]{2}(?:-[a-z]{2})?/)?articles/(\d+)[^\s)\"'<>]*", re.I)
COLLECTION_URL_RE = re.compile(
    r"https?://(?:www\.)?(?:oloid\.help|intercom\.help/oloid)/\S*collections/", re.I)
MD_LINK_RE = re.compile(r"\[([^\]\n]*)\]\((https?://[^)\s]+)\)")
HREF_RE = re.compile(r'(href=")(https?://[^"]+)(")')
TITLE_LINE_RE = re.compile(r"^title:\s*(.+)$", re.M)
SIDEBAR_LINE_RE = re.compile(r"^sidebarTitle:.*\n", re.M)


def iter_mdx(root, build_nav):
    """(docs-relative path, absolute path) of every page in the project."""
    skip = set(build_nav.SKIP_DIRS) | {"ask-oloid-worker", "node_modules"}
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in skip and not d.startswith("."))
        for name in sorted(filenames):
            if name.endswith(".mdx"):
                path = os.path.join(dirpath, name)
                yield os.path.relpath(path, root).replace(os.sep, "/"), path


def read_title(text):
    m = TITLE_LINE_RE.search(text[:2000])
    if not m:
        return ""
    raw = m.group(1).strip()
    try:
        return json.loads(raw) if raw.startswith('"') else raw.strip("'")
    except ValueError:
        return raw.strip('"')


def article_index(root, build_nav, nav_dirs=None):
    """{intercom article id: (page path, title)}, read back from the pages.

    Only pages inside a group navigation.json still declares are indexed
    (`nav_dirs`, drafts/ copies included). Otherwise a run made before the old
    layout is pruned would point links - including the hand-written guides',
    which are never regenerated - at pages that are about to be deleted.
    """
    index = {}
    for rel, path in iter_mdx(root, build_nav):
        if nav_dirs is not None:
            directory = os.path.dirname(rel)
            if directory.startswith("drafts/"):
                directory = directory[len("drafts/"):]
            if directory not in nav_dirs and os.path.dirname(rel) not in nav_dirs:
                continue
        with open(path, encoding="utf-8") as fh:
            head = fh.read(3000)
        m = SOURCE_RE.search(head)
        if not m:
            continue
        known = index.get(m.group(1))
        if known and not known[0].startswith("drafts/"):
            continue                        # the published copy wins
        index[m.group(1)] = (rel[:-4], read_title(head))
    return index


def rewrite_article_links(body, index, stats):
    def resolve(url):
        if COLLECTION_URL_RE.match(url):
            stats["links_collection"] += 1
            return None
        m = ARTICLE_URL_RE.fullmatch(url)
        if not m:
            return None
        hit = index.get(m.group(1))
        if not hit:
            stats["links_unresolved"] += 1
            stats["unresolved_ids"].add(m.group(1))
            return None
        stats["links_fixed"] += 1
        return hit

    def md(m):
        text, url = m.group(1), m.group(2)
        hit = resolve(url)
        if not hit:
            return m.group(0)
        path, title = hit
        if text.strip() == url or ARTICLE_URL_RE.fullmatch(text.strip()):
            text = mdx_escape(title)            # a bare URL reads better as the title
        return "[%s](/%s)" % (text, path)

    def href(m):
        hit = resolve(m.group(2))
        return "%s/%s%s" % (m.group(1), hit[0], m.group(3)) if hit else m.group(0)

    out = []
    for line, fenced in split_fences(body):
        if not fenced:
            line = HREF_RE.sub(href, MD_LINK_RE.sub(md, line))
        out.append(line)
    return "\n".join(out)


def fix_sidebar_title(head):
    """Recompute sidebarTitle in a frontmatter block from its title."""
    title = read_title(head)
    if not title:
        return head
    want = short_title(title)
    head = SIDEBAR_LINE_RE.sub("", head)
    if want and want != title:
        head = TITLE_LINE_RE.sub(lambda m: "%s\nsidebarTitle: %s" % (m.group(0), json.dumps(want)),
                                 head, count=1)
    return head


# --------------------------------------------------------------------------
# SEO frontmatter
# --------------------------------------------------------------------------
#  Everything here sits between the --- lines, so none of it renders on the
#  page. Mintlify turns `description`, `keywords`, `canonical`, `og:*` and
#  `twitter:*` into <meta> tags for crawlers, indexes `keywords` in site
#  search, and ranks results with `boost`. `section` / `product` /
#  `subsection` are custom fields, hidden as well.
#
#  The pass reruns on every polish, so the derived values follow a page when
#  it moves. Intercom's own keywords sit above DERIVED_KEYWORDS_MARK and are
#  never touched; everything below it is rebuilt.
# --------------------------------------------------------------------------

DERIVED_KEYWORDS_MARK = "  # derived by intercom_to_mintlify.py - rebuilt on every polish"
SEO_KEYS = ("canonical", "og:title", "og:description", "twitter:title",
            "twitter:description", "boost", "section", "product", "subsection")
MAX_KEYWORDS = 15
BOOST_VIDEOS = 0.7      # a video-only page ranks below the written guide
BOOST_DRAFTS = 0.5      # Drafts tab pages (drafts, unassigned, excluded) rank last
GENERIC_HEADING_RE = re.compile(
    r"^(introduction|overview|prerequisites?|steps?|procedure|additional information|"
    r"related articles?|notes?|summary|conclusion|keywords|faqs?|videos?|contents?|"
    r"table of contents|purpose|scope|steps? (to|for))$", re.I)
# Drafts tab labels describe triage state, not content: never keywords.
NON_KEYWORD_CRUMBS = {"Videos", "Unassigned", "Unassigned in Intercom",
                      "Collection not in navigation", "Excluded"}
# Acronyms, renames and spelling variants people search with. Matched against
# the title, the section path and the headings - not the whole body - so a
# passing mention does not add a keyword. Acronyms match in capitals only,
# so "Tap Next" is not the Tenant Admin Portal.
SYNONYMS = [
    (r"(?i:\bpasswordless\b)", ["passwordless login"]),
    (r"\bSSO\b|(?i:single sign-on)", ["SSO", "single sign-on"]),
    (r"\bMFA\b|(?i:multi-factor)", ["MFA", "multi-factor authentication"]),
    (r"\b2FA\b|(?i:two-factor)", ["2FA", "two-factor authentication"]),
    (r"(?i:\bentra\b|azure ad)", ["Microsoft Entra ID", "Azure AD"]),
    (r"\bQR\b", ["QR code"]),
    (r"(?i:device ?lock)", ["DeviceLock", "device lock"]),
    (r"\bTAP\b|(?i:tenant admin portal)", ["Tenant Admin Portal", "admin portal"]),
    (r"(?i:\bokta\b)", ["Okta"]),
    (r"(?i:\bkiosk\b)", ["kiosk mode"]),
]
VIDEOS_DIR = "videos"
FM_KEY_RE = re.compile(r'^("?)([A-Za-z][\w:.-]*)\1[ \t]*:')


def page_sections(nav, build_nav):
    """{group directory: crumbs} for every group, drafts/ mirror included.

    A mirrored draft keeps its home's crumbs, so a draft Windows page still
    says Platforms & Solutions > Windows; it is told apart by `boost`.
    """
    out = {}
    for _grp, parts, crumbs in build_nav.iter_groups(nav):
        out["/".join(parts)] = [str(c) for c in crumbs]
    drafts = build_nav.drafts_tab(nav) or {}
    if drafts.get("slug"):
        for directory, crumbs in list(out.items()):
            out.setdefault("%s/%s" % (drafts["slug"], directory), crumbs)
    return out


def section_for(rel, sections):
    """Crumbs of the closest declared group above page `rel`."""
    directory = os.path.dirname(rel)
    while directory:
        if directory in sections:
            return sections[directory]
        directory = os.path.dirname(directory)
    return []


def heading_keywords(body):
    out = []
    for line, fenced in split_fences(body):
        m = None if fenced else HEADING_RE.match(line)
        if not m or len(m.group(1)) not in (2, 3):
            continue
        text = clean_heading_text(re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", m.group(2)))
        text = re.sub(r"[*`_]+", "", text)
        text = re.sub(r"^(steps?|how) (to|for)\s+", "", text, flags=re.I).strip(" .:-")
        if 3 <= len(text) <= 80 and not GENERIC_HEADING_RE.match(text):
            out.append(text)
    return out


def derived_keywords(title, crumbs, body):
    """Search terms built from the page itself: its short title, the section
    path it lives in, its H2/H3 headings, and synonyms of what those name."""
    found = [short_title(title) or title]
    found += [c for c in crumbs[1:] if c and c not in NON_KEYWORD_CRUMBS]
    headings = heading_keywords(body)
    found += headings
    haystack = " | ".join([title] + crumbs + headings)
    for pattern, words in SYNONYMS:
        if re.search(pattern, haystack):
            found += words
    return found


def _fm_string(lines, key):
    for line in lines:
        m = FM_KEY_RE.match(line)
        if m and m.group(2) == key:
            raw = line[m.end():].strip()
            try:
                return json.loads(raw) if raw.startswith('"') else raw.strip("'")
            except ValueError:
                return raw.strip('"')
    return ""


def seo_frontmatter(head, rel, body, crumbs, base_url):
    """Rewrite a generated page's frontmatter with its hidden SEO fields."""
    lines = head.rstrip("\n").split("\n")
    if len(lines) < 2 or lines[0] != "---" or lines[-1] != "---":
        return head
    lines = lines[1:-1]

    kept, source_kw, in_kw, derived_part = [], [], False, False
    for line in lines:
        m = FM_KEY_RE.match(line)
        if m:
            in_kw = m.group(2) == "keywords"
            if in_kw or m.group(2) in SEO_KEYS:
                continue
        elif in_kw:
            if line == DERIVED_KEYWORDS_MARK:
                derived_part = True
            elif re.match(r"^[ \t]+-[ \t]", line) and not derived_part:
                raw = re.sub(r"^[ \t]+-[ \t]+", "", line).strip()
                try:
                    source_kw.append(json.loads(raw) if raw.startswith('"') else raw)
                except ValueError:
                    source_kw.append(raw.strip('"'))
            continue
        kept.append(line)

    title = _fm_string(kept, "title") or rel
    desc = _fm_string(kept, "description")
    if desc.startswith("{/"):           # an MDX comment taken for prose
        kept = [l for l in kept if not l.startswith("description:")]
        desc = ""
    if not desc:
        desc = first_sentence(body) or title
        at = next((i + 1 for i, l in enumerate(kept) if l.startswith(("sidebarTitle:", "title:"))),
                  len(kept))
        kept.insert(at, "description: %s" % json.dumps(desc))

    seen = {k.lower() for k in source_kw}
    derived = []
    for word in derived_keywords(title, crumbs, body):
        word = re.sub(r"\s+", " ", word).strip()
        if word and word.lower() not in seen and len(source_kw) + len(derived) < MAX_KEYWORDS:
            seen.add(word.lower())
            derived.append(word)
    if source_kw or derived:
        kept.append("keywords:")
        kept += ["  - %s" % json.dumps(k) for k in source_kw]
        if derived:
            kept.append(DERIVED_KEYWORDS_MARK)
            kept += ["  - %s" % json.dumps(k) for k in derived]

    url = "%s/%s" % (base_url.rstrip("/"), rel[:-4] if rel.endswith(".mdx") else rel)
    kept += [
        '"canonical": %s' % json.dumps(url),
        '"og:title": %s' % json.dumps(title),
        '"og:description": %s' % json.dumps(desc),
        '"twitter:title": %s' % json.dumps(title),
        '"twitter:description": %s' % json.dumps(desc),
    ]
    if rel.startswith("drafts/"):
        kept.append("boost: %s" % BOOST_DRAFTS)
    elif "/%s/" % VIDEOS_DIR in "/%s" % rel:
        kept.append("boost: %s" % BOOST_VIDEOS)
    if crumbs:
        kept.append("section: %s" % json.dumps(crumbs[0]))
    if len(crumbs) > 1:
        kept.append("product: %s" % json.dumps(crumbs[1]))
    if len(crumbs) > 2:
        kept.append("subsection: %s" % json.dumps(" > ".join(crumbs[2:])))
    return "---\n%s\n---\n" % "\n".join(kept)


# --------------------------------------------------------------------------
# Lint: what is still wrong with a finished page
# --------------------------------------------------------------------------
#  Run over every page --migrate wrote, after the polish, so it reports what a
#  reader would actually see. Nothing is changed here; each finding becomes an
#  entry in the page's `issues` in the manifest.
# --------------------------------------------------------------------------

REMOTE_IMAGE_RE = re.compile(r"!\[[^\]]*\]\((https?://[^)\s]+)\)|<img\b[^>]*\bsrc=\"(https?://[^\"]+)\"")
RAW_HTML_RE = re.compile(r"</?(div|span|p|table|thead|tbody|tr|td|th|ul|ol|li|b|i|u|strong|em|"
                         r"h[1-6]|blockquote|pre|code|font|center|section)\b[^>]*>", re.I)
GLUED_IMAGE_RE = re.compile(r"\S[ \t]*!\[[^\]]*\]\(/|!\[[^\]]*\]\([^)]*\)[ \t]*[A-Za-z]")
CALLOUT_NAMES = ("Note", "Warning", "Tip", "Info", "Check", "Danger", "Frame")


def lint_page(text):
    """[{"type", "detail"}] for one finished page; empty when it is clean."""
    issues = []

    def add(kind, detail):
        issues.append({"type": kind, "detail": detail})

    m = re.match(r"---\n.*?\n---\n", text, re.S)
    body = text[m.end():] if m else text
    if not m:
        add("frontmatter", "no frontmatter block")

    prose, fence_open = [], False
    for line, fenced in split_fences(body):
        if FENCE_RE.match(line):
            fence_open = not fence_open
        if not fenced:
            prose.append(line)
    if fence_open:
        add("code fence", "a ``` code block is never closed")
    # {/* ... */} comments render nothing - the Source line names oloid.help
    prose = re.sub(r"\{/\*.*?\*/\}", "", "\n".join(prose), flags=re.S)

    for name in CALLOUT_NAMES:
        opened = len(re.findall(r"<%s\b(?![^>]*/>)" % name, prose))
        closed = prose.count("</%s>" % name)
        if opened != closed:
            add("unbalanced component", "<%s> opened %d time(s), closed %d" % (name, opened, closed))
    for line in prose.splitlines():
        if re.match(r"^# ", line):
            add("h1 in body", line.strip()[:120])
    for mm in REMOTE_IMAGE_RE.finditer(prose):
        add("remote image", (mm.group(1) or mm.group(2))[:200])
    for mm in RAW_HTML_RE.finditer(prose):
        add("raw html", mm.group(0)[:120])
    for mm in ARTICLE_URL_RE.finditer(prose):
        add("link to oloid.help", "article %s was not migrated: %s" % (mm.group(1), mm.group(0)[:160]))
    for mm in re.finditer(r"\]\(#h_[0-9a-f]+\)", prose):
        add("dead anchor", mm.group(0)[:80])
    for mm in re.finditer(r"(?<!!)\[\s*\]\([^)]*\)", prose):
        add("empty link text", mm.group(0)[:120])
    for mm in IMAGE_MD_RE.finditer(prose):
        if GENERIC_ALT_RE.search(mm.group(1)):          # what the polish could not fix
            add("generic alt text", mm.group(0)[:120])
    for line in prose.splitlines():
        # "4. ![..](..)" is a step that is only a screenshot, not glued text
        bare = re.sub(r"^\s*(?:\d+[.)]|[-*+])\s+(?=!\[)", "", line)
        # a table cell is one line: its images can only sit inline
        if line.lstrip().startswith("|"):
            continue
        if GLUED_IMAGE_RE.search(bare) and "oloid-icon" not in line:
            add("image glued to text", line.strip()[:160])
    # &lt; &gt; &#123; are deliberate MDX escapes; these are leftovers
    for mm in re.finditer(r"&(?:nbsp|amp;\w+|#160|zwnj|zwj|shy);", prose):
        add("html entity", "literal %s left in the text" % mm.group(0))
        break
    return issues


def collect_issues(root, records, img_stats, dry_pages=None):
    """Attach image failures and lint findings to each manifest record.

    On a real run each written page is read back from disk, after the polish.
    On --dry-run nothing was written, so the page text kept in `dry_pages` is
    polished in memory instead; links to oloid.help are not reported there,
    because they are only resolved against pages that exist on disk.
    """
    by_id = {rec["id"]: rec for rec in records}
    failed_urls = {}                    # article id -> image URLs without ?query
    for fail in img_stats.get("failed") or []:
        rec = by_id.get(fail["article"])
        failed_urls.setdefault(fail["article"], set()).add(fail["url"].split("?")[0])
        if rec is not None:
            rec["issues"].append({"type": "image download failed",
                                  "detail": "%s - %s (the page links the remote URL, which "
                                            "may expire)" % (fail["error"], fail["url"][:200])})
    for kind, label in (("oversize", "image over 20 MB"), ("large", "image over 5 MB")):
        for rel, size in img_stats.get(kind) or []:
            parts = rel.strip("/").split("/")
            rec = by_id.get(parts[2] if len(parts) > 3 else None)
            if rec is not None:
                rec["issues"].append({"type": label,
                                      "detail": "%s (%.1f MB)" % (rel, size / 1048576.0)})

    stats = new_polish_stats()
    for rec in records:
        if rec["status"] != "written" or not rec["file"]:
            continue
        rel = rec["file"][:-4]
        if dry_pages is not None and rel in dry_pages:
            text = dry_pages[rel]
            m = re.match(r"---\n.*?\n---\n", text, re.S)
            head, body = (m.group(0), text[m.end():]) if m else ("", text)
            text = head + polish_images(body, rec["title"], root, stats)
            found = [i for i in lint_page(text) if i["type"] != "link to oloid.help"]
        else:
            try:
                with open(os.path.join(root, *rec["file"].split("/")), encoding="utf-8") as fh:
                    found = lint_page(fh.read())
            except OSError as exc:
                found = [{"type": "page missing", "detail": str(exc)}]
        # a failed download also shows up as a remote image; report it once
        failed = failed_urls.get(rec["id"], set())
        rec["issues"].extend(i for i in found
                             if not (i["type"] == "remote image"
                                     and i["detail"].split("?")[0] in failed))


def new_polish_stats():
    return {"pages": 0, "changed": 0, "icons": 0, "alts": 0, "split": 0,
            "links_fixed": 0, "links_unresolved": 0, "links_collection": 0,
            "unresolved_ids": set(), "seo": 0}


def polish_tree(root, build_nav, dry_run=False, stats=None, base_url=None):
    """Apply the polish to every page. Images, sidebar titles and the SEO
    frontmatter are only touched on generated pages; links are fixed
    everywhere, hand-written Getting Started guides included."""
    stats = stats or new_polish_stats()
    base_url = base_url or DOCS_BASE_URL
    nav = build_nav.load_nav(root)
    nav_dirs = {"/".join(parts) for _g, parts, _c in build_nav.iter_groups(nav)}
    sections = page_sections(nav, build_nav)
    index = article_index(root, build_nav, nav_dirs)
    for rel, path in iter_mdx(root, build_nav):
        with open(path, encoding="utf-8") as fh:
            text = fh.read()
        m = re.match(r"---\n.*?\n---\n", text, re.S)
        head, body = (m.group(0), text[m.end():]) if m else ("", text)
        stats["pages"] += 1
        if GENERATED_MARKER in text:
            head = fix_sidebar_title(head)
            body = polish_images(body, read_title(head) or rel, root, stats)
        body = rewrite_article_links(body, index, stats)
        if text.endswith("\n") and not body.endswith("\n"):
            body += "\n"                    # the line-wise passes drop it
        if GENERATED_MARKER in text:
            seo = seo_frontmatter(head, rel, body, section_for(rel, sections), base_url)
            stats["seo"] += seo != head
            head = seo
        new = head + body
        if new != text:
            stats["changed"] += 1
            if not dry_run:
                with open(path, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(new)
    return stats


def print_polish(stats):
    print("Polish       : %d of %d pages changed" % (stats["changed"], stats["pages"]))
    print("               %d alt texts written, %d icons sized inline, "
          "%d glued screenshots split out" % (stats["alts"], stats["icons"], stats["split"]))
    print("SEO          : %d pages' keywords / meta tags updated" % stats["seo"])
    print("Links        : %d oloid.help links now point at Mintlify pages"
          % stats["links_fixed"])
    if stats["links_unresolved"] or stats["links_collection"]:
        print("               %d still point at oloid.help: %d to %d article(s) that were "
              "not migrated, %d to collections"
              % (stats["links_unresolved"] + stats["links_collection"],
                 stats["links_unresolved"], len(stats["unresolved_ids"]),
                 stats["links_collection"]))
        if stats["unresolved_ids"]:
            print("               article ids: %s"
                  % ", ".join(sorted(stats["unresolved_ids"])[:30]))


