def migrate_to_tabs(nav):
    """Navigation accepts pages OR tabs, not both. Move any existing top-level
    pages/groups into a tab so nothing is lost."""
    if "tabs" in nav:
        return nav, None
    carried = None
    icon = icon_for(EXISTING_PAGES_TAB)
    if nav.get("groups"):
        carried = {"tab": EXISTING_PAGES_TAB, "groups": nav.pop("groups")}
    elif nav.get("pages"):
        carried = {"tab": EXISTING_PAGES_TAB, "pages": nav.pop("pages")}
    if carried and icon:
        carried["icon"] = icon
    nav["tabs"] = [carried] if carried else []
    return nav, (EXISTING_PAGES_TAB if carried else None)


def apply_theme(docs):
    """Set the theme and turn on breadcrumb eyebrows above page titles."""
    changed = []
    if THEME and docs.get("theme") != THEME:
        docs["theme"] = THEME
        changed.append("theme=%s" % THEME)
    if EYEBROWS:
        styling = docs.setdefault("styling", {})
        if styling.get("eyebrows") != EYEBROWS:
            styling["eyebrows"] = EYEBROWS
            changed.append("eyebrows=%s" % EYEBROWS)
    if FONTS:
        if docs.get("fonts") != FONTS:
            docs["fonts"] = FONTS
            families = sorted({f["family"] for f in FONTS.values() if isinstance(f, dict)}) \
                if "family" not in FONTS else [FONTS["family"]]
            changed.append("fonts=%s" % "+".join(families))
    elif "fonts" in docs:
        # FONTS is deliberately empty: the family is a system stack set in
        # style.css, and a leftover docs.json webfont would override it.
        docs.pop("fonts")
        changed.append("fonts=system-ui (from style.css)")
    changed += strip_placeholder_chrome(docs)
    return changed


def is_placeholder(url):
    """True for a starter-kit link: a mintlify.com URL, or a social account
    whose handle is mintlify (https://x.com/mintlify and friends)."""
    url = str(url or "").lower().rstrip("/")
    if any(host in url for host in PLACEHOLDER_HOSTS):
        return True
    return url.endswith("/mintlify") or url.endswith("/company/mintlify")


def strip_placeholder_chrome(docs):
    """Drop starter-kit navigation that still points at mintlify.com.

    Every removal is reported so nothing disappears silently, and a link to a
    real Oloid URL is never touched.
    """
    removed = []

    if docs.get("name") in (None, "", "Mintlify Starter Kit") and SITE_NAME:
        if docs.get("name") != SITE_NAME:
            removed.append("name %r -> %r" % (docs.get("name"), SITE_NAME))
            docs["name"] = SITE_NAME

    nav = docs.get("navigation", {})
    anchors = nav.get("global", {}).get("anchors")
    if isinstance(anchors, list):
        keep = [a for a in anchors if not is_placeholder(a.get("href"))]
        for a in anchors:
            if a not in keep:
                removed.append("anchor %r" % a.get("anchor"))
        if keep:
            nav["global"]["anchors"] = keep
        else:
            nav.get("global", {}).pop("anchors", None)
            if not nav.get("global"):
                nav.pop("global", None)

    navbar = docs.get("navbar", {})
    links = navbar.get("links")
    if isinstance(links, list):
        keep = [l for l in links if not is_placeholder(l.get("href"))]
        for l in links:
            if l not in keep:
                removed.append("navbar link %r" % l.get("label"))
        if keep:
            navbar["links"] = keep
        else:
            navbar.pop("links", None)
    primary = navbar.get("primary")
    if isinstance(primary, dict) and is_placeholder(primary.get("href")):
        removed.append("navbar button %r" % primary.get("label"))
        navbar.pop("primary", None)
    if not navbar:
        docs.pop("navbar", None)

    socials = docs.get("footer", {}).get("socials")
    if isinstance(socials, dict):
        keep = {k: v for k, v in socials.items() if not is_placeholder(v)}
        for k in socials:
            if k not in keep:
                removed.append("footer social %r" % k)
        if keep:
            docs["footer"]["socials"] = keep
        else:
            docs.get("footer", {}).pop("socials", None)
            if not docs.get("footer"):
                docs.pop("footer", None)

    if CONTEXTUAL_OPTIONS:
        current = docs.get("contextual", {}).get("options")
        if current != CONTEXTUAL_OPTIONS:
            removed.append("contextual options %d -> %d"
                           % (len(current or []), len(CONTEXTUAL_OPTIONS)))
            docs.setdefault("contextual", {})["options"] = list(CONTEXTUAL_OPTIONS)

    return removed


def write_style_css(root, dry_run):
    """Write style.css, which Mintlify auto-loads from the repo root.

    An existing file is only replaced when this script wrote it; a hand-written
    style.css is left alone and reported instead of being clobbered.
    """
    path = os.path.join(root, "style.css")
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as fh:
            existing = fh.read()
        if STYLE_MARKER not in existing:
            return "skipped (style.css exists and was not generated by this script)"
        if existing.strip() == STYLE_CSS.strip():
            return "unchanged"
    if dry_run:
        return "would write"
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(STYLE_CSS.lstrip("\n"))
    return "written"


def icon_for(label):
    return ICONS.get(label)


def backfill_icons(nav):
    """Attach icons from ICONS onto navigation entries that already exist.

    Used by --config-only so theme/icon changes can be applied to a docs.json
    without re-fetching every article.
    """
    added = []

    def visit(node):
        if isinstance(node, dict):
            for key in ("tab", "item", "group"):
                label = node.get(key)
                if isinstance(label, str) and "icon" not in node:
                    ic = icon_for(label)
                    if ic:
                        node["icon"] = ic
                        added.append(label)
            for value in node.values():
                visit(value)
        elif isinstance(node, list):
            for value in node:
                visit(value)

    visit(nav)
    return added


def find_or_create(items, key, value, extra):
    for entry in items:
        if entry.get(key) == value:
            # backfill an icon onto an entry created before ICONS knew about it
            if "icon" in extra and "icon" not in entry:
                entry["icon"] = extra["icon"]
            return entry, False
    entry = {key: value}
    entry.update(extra)
    items.append(entry)
    return entry, True


def upsert_page(nav, tab, menu, group, page_path):
    """Ensure tabs[tab].menu[menu].groups[group].pages contains page_path."""
    def with_icon(label, base):
        ic = icon_for(label)
        return dict(base, icon=ic) if ic else dict(base)

    tabs = nav.setdefault("tabs", [])
    tab_entry, _ = find_or_create(tabs, "tab", tab, with_icon(tab, {"menu": []}))

    # a tab created earlier by migration may hold pages/groups instead of menu
    if "menu" not in tab_entry:
        tab_entry["menu"] = []
    menu_list = tab_entry["menu"]

    menu_entry, _ = find_or_create(menu_list, "item", menu, with_icon(menu, {"groups": []}))
    if "groups" not in menu_entry:
        menu_entry["groups"] = []

    group_entry, _ = find_or_create(
        menu_entry["groups"], "group", group, with_icon(group, {"pages": []}))
    pages = group_entry.setdefault("pages", [])

    if page_path in pages:
        return "already linked"
    pages.append(page_path)
    return "linked"


