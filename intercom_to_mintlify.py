def plan(args, root):
    import csv
    build_nav, fetchlib = _helpers()
    nav = build_nav.load_nav(root)
    mapping = nav_group_dirs(nav, build_nav)
    rules = build_rules(nav, build_nav)
    excluded = excluded_keys(nav, build_nav)
    unmapped_dir = unmapped_directory(nav, build_nav)
    by_category = {}
    path = os.path.join(root, "output", "_all_articles.csv")
    if not os.path.exists(path):
        sys.stderr.write("ERROR: no %s - export the article list first (oloid.py)\n" % path)
        return 2

    counts, by_rule, unmapped = {}, [], {}
    with open(path, encoding="utf-8-sig") as fh:
        for row in csv.DictReader(fh):
            product = row.get("product") or fetchlib.UNASSIGNED
            collection = row.get("collection") or fetchlib.UNASSIGNED
            title = html.unescape(row.get("title") or "")
            directory, rule, category = place(product, collection, title, mapping, rules,
                                              build_nav, excluded, unmapped_dir)
            by_category[category] = by_category.get(category, 0) + 1
            label = "%s :: %s" % (html.unescape(product), html.unescape(collection))
            if category == "unmapped":
                unmapped.setdefault(label, []).append(row.get("article_id"))
            if not directory:
                continue
            slot = counts.setdefault(directory, [0, 0])
            slot[1 if row.get("state") == "draft" else 0] += 1
            if rule:
                by_rule.append((" > ".join(rule["crumbs"][1:]), title, label,
                                row.get("state")))

    print("")
    print("%-58s %9s %6s" % ("Section", "published", "drafts"))
    print("=" * 75)
    for tab in nav.get("tabs") or []:
        print(tab.get("tab"))
        rows = []
        tab_parts = [tab["slug"]] if tab.get("slug") else []

        def show(node, parts, depth):
            total = [0, 0]
            for grp in node.get("groups") or []:
                p = parts + ([grp["slug"]] if grp.get("slug") else [])
                at = len(rows)
                rows.append(None)
                sub = show(grp, p, depth + 1)
                own = counts.get("/".join(p), [0, 0])
                rows[at] = (depth, grp.get("group"), own[0] + sub[0], own[1] + sub[1])
                total[0] += own[0] + sub[0]
                total[1] += own[1] + sub[1]
            return total

        show(tab, tab_parts, 1)
        for item in tab.get("menu") or []:
            at = len(rows)
            rows.append(None)
            sub = show(item, tab_parts + ([item["slug"]] if item.get("slug") else []), 2)
            rows[at] = (1, item.get("item"), sub[0], sub[1])
        for depth, label, pub, drafts in rows:
            pad = "   " * depth
            print("%s%-*s %9d %6d" % (pad, 58 - len(pad), (label or "")[:58 - len(pad)],
                                     pub, drafts))
    print("")
    print("By category: %s" % ", ".join("%s %d" % kv for kv in sorted(by_category.items())))
    print("(excluded -> Drafts > Excluded; unassigned and unmapped -> Drafts > Unassigned)")
    print("")
    print("Placed by title rule - %d article(s):" % len(by_rule))
    for target, title, source, state in sorted(by_rule):
        print("   %-38s <- %s%s" % (target[:38], title[:80],
                                     "  [draft]" if state == "draft" else ""))
        print("   %-38s    from %s" % ("", source))
    if unmapped:
        print("")
        print("UNMAPPED - %d collection(s):" % len(unmapped))
        for coll, ids in sorted(unmapped.items(), key=lambda kv: -len(kv[1])):
            print("   %4d  %s" % (len(ids), coll))
    print("")
    print("Not simulated: video-only articles move to their section's Videos group,")
    print("and drafts go under drafts/ - both need the article body, so --migrate decides.")
    return 0


def migrate(args, root):
    """Fetch every article and file it under the navigation."""
    build_nav, fetchlib = _helpers()

    nav_path = os.path.join(root, NAV_FILE)
    if not os.path.exists(nav_path):
        sys.stderr.write("ERROR: no %s - run build_nav.py first\n" % nav_path)
        return 2
    with open(nav_path, "r", encoding="utf-8") as fh:
        nav = json.load(fh)
    mapping = nav_group_dirs(nav, build_nav)
    rules = build_rules(nav, build_nav)
    excluded = excluded_keys(nav, build_nav)
    unmapped_dir = unmapped_directory(nav, build_nav)

    sys.stderr.write("[1/3] GET /help_center/collections ...\n")
    _raw, paths = fetchlib.fetch_collections(args.api_key)
    sys.stderr.write("      %d collections\n" % len(paths))

    sys.stderr.write("[2/3] GET /articles ...\n")
    summaries = fetchlib.fetch_article_list(args.api_key, args.limit)
    sys.stderr.write("      %d articles\n" % len(summaries))

    sys.stderr.write("[3/3] GET /articles/{id} ...\n")
    cache = os.path.join(root, args.cache_dir, "articles")
    articles = fetchlib.fetch_article_bodies(args.api_key, summaries, cache,
                                             refresh=args.refresh)

    img_stats = {"saved": 0, "reused": 0, "bytes": 0,
                 "large": [], "oversize": [], "failed": []}
    written, skipped_empty, unmapped, by_rule = [], [], {}, []
    used_paths, touched = {}, set()
    records = []                       # one per article, for the manifest
    skipped_excluded = {}
    dry_pages = {}                     # --dry-run: rel -> page text never written

    for art in articles:
        article_id = str(art.get("id"))
        product, collection, full_path = fetchlib.resolve_placement(art, paths)
        title = html.unescape((art.get("title") or "Untitled").strip())
        record = manifest_record(art, title, product, collection, full_path)
        records.append(record)

        directory, rule, category = place(product, collection, title, mapping, rules,
                                          build_nav, excluded, unmapped_dir)
        record["category"] = category
        if category == "excluded":
            skipped_excluded.setdefault(record["intercom_collection"], []).append(article_id)
        elif category == "unmapped":
            unmapped.setdefault("%s :: %s" % (product, collection), []).append(article_id)
        if not directory:
            record["status"] = "unmapped"
            continue
        record["placed_by"] = "title rule" if rule else "collection"
        if rule:
            by_rule.append((" > ".join(rule["crumbs"][1:]), title,
                            html.unescape("%s :: %s" % (product, collection))))

        if not (art.get("body") or "").strip():
            skipped_empty.append((article_id, title))
            record["status"] = "empty in Intercom"
            record["issues"].append({"type": "empty body",
                                     "detail": "the article has no body in Intercom; no page written"})
            continue

        on_image = None
        if not args.no_download_images:
            def on_image(u, _id=article_id):
                return download_image(u, root, _id, args.dry_run, img_stats)

        try:
            body_mdx, images, videos = html_to_mdx(
                art.get("body") or "", on_image=on_image,
                alt_prefix=short_title(title, 40))
            body_mdx, keywords, audit = apply_template(body_mdx, mirror=True)
            body_mdx = drop_repeated_title(body_mdx, title)
        except Exception as exc:  # noqa: BLE001 - one bad article must not stop the run
            sys.stderr.write("  ! article %s did not convert: %r\n" % (article_id, exc))
            record["status"] = "conversion error"
            record["issues"].append({"type": "conversion error", "detail": repr(exc)[:300]})
            continue

        if not body_mdx.strip():
            skipped_empty.append((article_id, title + "  (body did not convert)"))
            record["status"] = "body did not convert"
            record["issues"].append({"type": "body did not convert",
                                     "detail": "the HTML converted to nothing; no page written"})
            continue

        if is_video_only(body_mdx):
            # the nearest Videos group, where there is one
            moved = build_nav.video_directory(nav, directory)
            if moved != directory:
                record["moved_to"].append("videos")
            directory = moved.replace("/", os.sep)
        if art.get("state") == "draft":
            # drafts/<same path>, listed under the Drafts tab; Excluded keeps its own
            moved = build_nav.draft_directory(nav, directory)
            if moved != directory.replace(os.sep, "/"):
                record["moved_to"].append("drafts")
            directory = moved.replace("/", os.sep)
        slug = page_slug(art)
        rel = "%s/%s" % (directory.replace(os.sep, "/"), slug)
        if rel in used_paths and used_paths[rel] != article_id:
            slug = "%s-%s" % (slug, article_id)      # two articles, one slug
            rel = "%s/%s" % (directory.replace(os.sep, "/"), slug)
        used_paths[rel] = article_id

        page = build_mdx(art, body_mdx, icon=DEFAULT_PAGE_ICON, keywords=keywords)
        if args.dry_run:
            dry_pages[rel] = page               # linted below, as if written
        else:
            abs_path = os.path.join(root, directory, slug + ".mdx")
            try:
                os.makedirs(os.path.dirname(abs_path), exist_ok=True)
                with open(abs_path, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(page)
            except OSError as exc:
                sys.stderr.write("  ! could not write %s: %s\n" % (abs_path, exc))
                record["status"] = "write failed"
                record["issues"].append({"type": "write failed", "detail": str(exc)})
                continue
        touched.add(directory)
        record.update({"status": "written", "file": rel + ".mdx", "mintlify_path": "/" + rel,
                       "mintlify_url": args.docs_url.rstrip("/") + "/" + rel,
                       "section_path": directory.replace(os.sep, "/"),
                       "keywords": keywords, "words": len(body_mdx.split()),
                       "images": len(images), "videos": len(videos)})
        written.append({"id": article_id, "title": title, "path": rel + ".mdx",
                        "words": len(body_mdx.split()), "images": len(images),
                        "videos": len(videos), "sections": audit.get("found", []),
                        "collection": "%s :: %s" % (product, collection)})

        if len(written) % 100 == 0:
            sys.stderr.write("      wrote %d pages\n" % len(written))

    dropped, pruned = 0, []
    if not args.dry_run:
        for directory in sorted(touched):
            dropped += 1 if drop_placeholder(os.path.join(root, directory)) else 0
        failed = [str(a.get("id")) for a in articles if a.get("_fetch_error")]
        if args.limit:
            sys.stderr.write("      --limit: stale pages kept (a partial run would "
                             "delete everything it did not fetch)\n")
        elif failed:
            sys.stderr.write("      %d article(s) failed to fetch (%s): stale pages kept, "
                             "so their existing pages survive. Re-run to clean up.\n"
                             % (len(failed), ", ".join(failed[:10])))
        else:
            nav_dirs = {"/".join(parts) for _g, parts, _c in build_nav.iter_groups(nav)}
            pruned = prune_stale(root, [w["path"] for w in written], nav_dirs, build_nav)

    sys.stderr.write("[4/4] polishing pages and links ...\n")
    polish = polish_tree(root, build_nav, dry_run=args.dry_run, base_url=args.docs_url)

    sys.stderr.write("      checking every page for leftover problems ...\n")
    collect_issues(root, records, img_stats, dry_pages)

    write_style_css(root, args.dry_run)
    manifest_path = write_manifest(root, nav, build_nav, records, args)

    print("")
    print("=" * 72)
    print("Intercom -> Mintlify%s" % ("  (DRY RUN - nothing written)" if args.dry_run else ""))
    print("=" * 72)
    print("Fetched      : %d articles in %d collections" % (len(articles), len(paths)))
    print("Written      : %d pages across %d groups" % (len(written), len(touched)))
    print("Skipped      : %d with an empty body" % len(skipped_empty))
    cats = {}
    for rec in records:
        cats[rec["category"]] = cats.get(rec["category"], 0) + 1
    print("Categories   : %s" % ", ".join("%s %d" % (k or "-", v)
                                          for k, v in sorted(cats.items(), key=str)))
    print("Excluded     : %d in %d collection(s), written to Drafts > Excluded (%s)"
          % (sum(len(v) for v in skipped_excluded.values()), len(skipped_excluded),
             ", ".join(sorted(skipped_excluded)) or "none"))
    print("Placeholders : %d removed (group now has real pages)" % dropped)
    print("Stale pages  : %d deleted (generated by an earlier run, not written this time)"
          % len(pruned))
    print("Images       : %d saved, %d reused, %d failed"
          % (img_stats["saved"], img_stats["reused"], len(img_stats["failed"])))
    print_polish(polish)
    print("Manifest     : %s  (every article, its status and its page)" % manifest_path)
    if by_rule:
        print("")
        print("PLACED BY TITLE - %d article(s), check these:" % len(by_rule))
        for target, title, source in sorted(by_rule):
            print("   %-38s <- %s" % (target[:38], title[:80]))
            print("   %-38s    from %s" % ("", source))
    if unmapped:
        total = sum(len(v) for v in unmapped.values())
        print("")
        print("UNMAPPED - %d collection(s), %d article(s) %s:"
              % (len(unmapped), total,
                 "in Drafts > Unassigned" if unmapped_dir else "not written"))
        for coll, ids in sorted(unmapped.items(), key=lambda kv: -len(kv[1])):
            print("   %4d  %s" % (len(ids), coll))
        print("   Add these to a group in navigation.json, then re-run.")
    if skipped_empty:
        print("")
        print("EMPTY IN INTERCOM - %d:" % len(skipped_empty))
        for article_id, title in skipped_empty[:25]:
            print("   %-10s %s" % (article_id, title[:70]))
        if len(skipped_empty) > 25:
            print("   ... and %d more" % (len(skipped_empty) - 25))
    with_issues = [r for r in records if r["issues"]]
    if with_issues:
        kinds = {}
        for rec in with_issues:
            for kind in {i["type"] for i in rec["issues"]}:
                kinds[kind] = kinds.get(kind, 0) + 1
        print("")
        print("ISSUES - %d article(s) need a look (details: lists.has-issues in %s):"
              % (len(with_issues), MANIFEST_FILE))
        for kind, n in sorted(kinds.items(), key=lambda kv: -kv[1]):
            print("   %4d  %s" % (n, kind))
    print("")

    if not args.dry_run and not args.no_nav:
        print("Rebuilding docs.json ...")
        import subprocess
        subprocess.call([sys.executable, os.path.join(root, "build_nav.py")])
    else:
        print("Next: python build_nav.py     # rebuild docs.json from what is on disk")
    return 0


def main():
    parser = argparse.ArgumentParser(
        description="Fetch Intercom articles by ID and wire them into Mintlify docs.json."
    )
    parser.add_argument(
        "--api-key", default=None,
        help="Intercom bearer token. Falls back to $INTERCOM_API_KEY, then "
             "./.intercom_token, then the API_KEY constant.",
    )
    parser.add_argument("--root", default=".", help="Mintlify project root (default: .)")
    parser.add_argument("--docs-json", default=None, help="Path to docs.json (default: <root>/docs.json)")
    parser.add_argument("--no-download-images", action="store_true",
                        help="Hotlink the Intercom CDN instead of saving images locally. "
                             "Not recommended: Intercom's image URLs are signed and expire.")
    parser.add_argument("--dry-run", action="store_true", help="Report only; write nothing.")
    parser.add_argument("--config-only", action="store_true",
                        help="Only apply theme, breadcrumbs and icons to docs.json. "
                             "Fetches nothing and leaves existing pages untouched.")
    parser.add_argument("--reformat", action="store_true",
                        help="Re-apply the document template and style.css to the .mdx "
                             "pages already in the repo. Needs no Intercom token.")
    parser.add_argument("--migrate", action="store_true",
                        help="Fetch EVERY article and file it under navigation.json. "
                             "Uses GET /help_center/collections, /articles and "
                             "/articles/{id} - no write endpoints, ever.")
    parser.add_argument("--limit", type=int, default=None,
                        help="--migrate: stop after N articles (smoke test).")
    parser.add_argument("--refresh", action="store_true",
                        help="--migrate: ignore the cache and re-fetch every article.")
    parser.add_argument("--cache-dir", default="intercom_export",
                        help="--migrate: where per-article JSON is cached "
                             "(default: intercom_export).")
    parser.add_argument("--no-nav", action="store_true",
                        help="--migrate: skip the build_nav.py run at the end.")
    parser.add_argument("--docs-url", default=DOCS_BASE_URL,
                        help="--migrate: base URL of the published docs, for the "
                             "manifest's mintlify_url (default: %s)." % DOCS_BASE_URL)
    parser.add_argument("--plan", action="store_true",
                        help="Show where every article in output/_all_articles.csv would "
                             "land under navigation.json, and which were placed by title. "
                             "Needs no token and writes nothing.")
    parser.add_argument("--polish", action="store_true",
                        help="Re-apply the screenshot, icon, alt-text, sidebar-title and "
                             "link fixes to the pages already on disk. Needs no token. "
                             "--migrate runs this at the end anyway.")
    args = parser.parse_args()

    if args.plan:
        return plan(args, os.path.abspath(args.root))

    if args.polish:
        import build_nav
        root = os.path.abspath(args.root)
        stats = polish_tree(root, build_nav, dry_run=args.dry_run,
                            base_url=getattr(args, "docs_url", None))
        style_status = write_style_css(root, args.dry_run)
        print("")
        print_polish(stats)
        print("style.css    : %s" % style_status)
        return 0

    try:
        import intercom_fetch
        args.api_key = intercom_fetch.resolve_token(args.api_key)
    except ImportError:
        args.api_key = (args.api_key
                        or os.environ.get("INTERCOM_API_KEY")
                        or os.environ.get("INTERCOM_TOKEN")
                        or API_KEY)

    if args.reformat:
        root = os.path.abspath(args.root)
        rows = reformat_tree(root, args.dry_run)
        style_status = write_style_css(root, args.dry_run)

        docs_path = args.docs_json or os.path.join(root, "docs.json")
        theme_changes = []
        if os.path.exists(docs_path):
            with open(docs_path, "r", encoding="utf-8") as fh:
                docs = json.load(fh)
            theme_changes = apply_theme(docs)
            if theme_changes and not args.dry_run:
                with open(docs_path, "w", encoding="utf-8", newline="\n") as fh:
                    json.dump(docs, fh, indent=2, ensure_ascii=False)
                    fh.write("\n")

        print("")
        print("=" * 72)
        print("Reformat to template%s" % ("  (DRY RUN - nothing written)" if args.dry_run else ""))
        print("=" * 72)
        print("Pages     : %d generated, %d rewritten"
              % (len(rows), sum(1 for r in rows if r["changed"])))
        print("style.css : %s" % style_status)
        if theme_changes:
            print("docs.json :")
            for change in theme_changes:
                print("              - %s" % change)
        print("")
        for r in rows:
            print("%s %s" % ("~~" if r["changed"] else "ok", r["rel"]))
            print("     sections : %s" % (" > ".join(r["audit"]["found"]) or "none recognised"))
            if r["audit"]["missing"]:
                print("     MISSING  : %s  (add by hand; nothing was invented)"
                      % ", ".join(r["audit"]["missing"]))
            print("     keywords : %s" % (", ".join(r["keywords"])
                                          or "already in frontmatter (none left in body)"))
            print("")
        print("Preview locally:")
        print("    mint dev          # http://localhost:3000")
        print("")
        return 0

    if args.migrate:
        if not args.api_key:
            parser.error(
                "--migrate needs a bearer token. Either:\n"
                "  1. put it in ./.intercom_token   (gitignored, one line), or\n"
                "  2. $env:INTERCOM_API_KEY = 'your_token'   (PowerShell), or\n"
                "  3. python intercom_to_mintlify.py --migrate --api-key your_token"
            )
        return migrate(args, os.path.abspath(args.root))

    if not args.api_key and not args.config_only:
        parser.error(
            "No bearer token. Either:\n"
            "  1. set API_KEY = \"your_token\" at the top of this file, or\n"
            "  2. $env:INTERCOM_API_KEY = 'your_token'   (PowerShell), or\n"
            "  3. python intercom_to_mintlify.py --api-key your_token"
        )

    root = os.path.abspath(args.root)
    docs_path = args.docs_json or os.path.join(root, "docs.json")
    if not os.path.exists(docs_path):
        sys.stderr.write("ERROR: no docs.json at %s\n" % docs_path)
        return 2

    with open(docs_path, "r", encoding="utf-8") as fh:
        docs = json.load(fh)
    theme_changes = apply_theme(docs)
    nav = docs.setdefault("navigation", {})
    nav, migrated = migrate_to_tabs(nav)

    if args.config_only:
        icons_added = backfill_icons(nav)
        style_status = write_style_css(root, args.dry_run)
        if not args.dry_run:
            with open(docs_path, "w", encoding="utf-8", newline="\n") as fh:
                json.dump(docs, fh, indent=2, ensure_ascii=False)
                fh.write("\n")
        print("")
        print("=" * 72)
        print("docs.json refresh%s" % ("  (DRY RUN)" if args.dry_run else ""))
        print("=" * 72)
        print("Applied  : %s" % (", ".join(theme_changes) or "no theme change needed"))
        if migrated:
            print("Migrated : top-level navigation moved into the %r tab" % migrated)
        print("Icons    : %s" % (", ".join(icons_added) if icons_added
                                 else "none added (all entries already had one)"))
        print("style.css: %s" % style_status)
        print("File     : %s" % docs_path)
        print("")
        print("Note: existing .mdx pages are untouched. Re-run without --config-only")
        print("      to regenerate them with sidebarTitle, icons and image alt text.")
        print("")
        return 0

    results = []
    used_paths = {}
    img_stats = {"saved": 0, "reused": 0, "bytes": 0,
                 "large": [], "oversize": [], "failed": []}

    for spec in ARTICLE_MAP:
        article_id = spec["id"]
        row = {"id": article_id, "tab": spec["tab"], "menu": spec["menu"],
               "group": spec["group"], "status": "", "title": "", "path": "",
               "words": 0, "images": 0, "videos": 0}
        try:
            article = fetch_article(article_id, args.api_key)
        except IntercomError as exc:
            row["status"] = "FAILED: %s" % exc
            results.append(row)
            sys.stderr.write("  ! %s\n" % exc)
            continue

        title = html.unescape((article.get("title") or "Untitled").strip())
        row["title"] = title

        on_image = None
        if not args.no_download_images:
            def on_image(u, _id=article_id):
                return download_image(u, root, _id, args.dry_run, img_stats)

        body_mdx, images, videos = html_to_mdx(
            article.get("body") or "", on_image=on_image, alt_prefix=short_title(title, 40))
        body_mdx, keywords, audit = apply_template(body_mdx)
        row["keywords"] = keywords
        row["audit"] = audit
        row["words"] = len(body_mdx.split())
        row["images"] = len(images)
        row["videos"] = len(videos)

        rel_dir = os.path.join(slugify(spec["tab"]), slugify(spec["menu"]), slugify(spec["group"]))
        slug = page_slug(article)
        nav_path = "%s/%s" % (rel_dir.replace(os.sep, "/"), slug)
        if nav_path in used_paths and used_paths[nav_path] != article_id:
            slug = "%s-%s" % (slug, article_id)
            nav_path = "%s/%s" % (rel_dir.replace(os.sep, "/"), slug)
        used_paths[nav_path] = article_id

        abs_path = os.path.join(root, rel_dir, slug + ".mdx")
        row["path"] = nav_path + ".mdx"

        if not article.get("body"):
            row["status"] = "EMPTY BODY"
        elif not body_mdx:
            row["status"] = "BODY DID NOT CONVERT"
        else:
            row["status"] = "OK"

        if not args.dry_run:
            os.makedirs(os.path.dirname(abs_path), exist_ok=True)
            with open(abs_path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(build_mdx(article, body_mdx,
                                   icon=spec.get("icon", DEFAULT_PAGE_ICON),
                                   keywords=keywords))

        link = upsert_page(nav, spec["tab"], spec["menu"], spec["group"], nav_path)
        row["nav"] = link
        results.append(row)

    style_status = write_style_css(root, args.dry_run)

    if not args.dry_run:
        with open(docs_path, "w", encoding="utf-8", newline="\n") as fh:
            json.dump(docs, fh, indent=2, ensure_ascii=False)
            fh.write("\n")

    # ---------------------------- report ----------------------------------
    print("")
    print("=" * 72)
    print("Intercom -> Mintlify%s" % ("  (DRY RUN - nothing written)" if args.dry_run else ""))
    print("=" * 72)
    if theme_changes:
        print("Applied    : %s" % ", ".join(theme_changes))
    if migrated:
        print("Moved existing top-level navigation into the %r tab." % migrated)
    if theme_changes or migrated:
        print("")

    ok = [r for r in results if r["status"] == "OK"]
    bad = [r for r in results if r["status"] != "OK"]

    print("Requested : %d" % len(ARTICLE_MAP))
    print("Fetched   : %d" % len(ok))
    print("Problems  : %d" % len(bad))
    print("")
    for r in results:
        mark = "OK " if r["status"] == "OK" else "!! "
        print("%s%s" % (mark, r["title"] or "(no title)"))
        print("     id      : %s" % r["id"])
        print("     nav     : %s > %s > %s" % (r["tab"], r["menu"], r["group"]))
        print("     file    : %s" % r["path"])
        print("     content : %d words, %d image(s), %d video(s)"
              % (r["words"], r["images"], r["videos"]))
        audit = r.get("audit") or {}
        if audit:
            print("     sections: %s" % (" > ".join(audit.get("found") or []) or "none recognised"))
            if audit.get("missing"):
                print("     MISSING : %s  (add by hand; nothing was invented)"
                      % ", ".join(audit["missing"]))
        if r.get("keywords"):
            print("     keywords: %s" % ", ".join(r["keywords"]))
        print("     status  : %s (%s)" % (r["status"], r.get("nav", "-")))
        print("")

    if not args.no_download_images:
        mb = img_stats["bytes"] / (1024.0 * 1024.0)
        print("Images    : %d saved, %d already present, %.1f MB total"
              % (img_stats["saved"], img_stats["reused"], mb))
        for rel, size in img_stats["oversize"]:
            print("   OVER 20MB LIMIT: %s (%.1f MB) - Mintlify will reject this; "
                  "compress it or host it on a CDN" % (rel, size / (1024.0 * 1024.0)))
        for rel, size in img_stats["large"]:
            print("   large  : %s (%.1f MB)" % (rel, size / (1024.0 * 1024.0)))
        for fail in img_stats["failed"]:
            print("   FAILED : %s (%s; left as remote URL)" % (fail["url"][:90], fail["error"]))
        print("")

    if bad:
        print("NOT imported cleanly:")
        for r in bad:
            print("   - %s: %s" % (r["id"], r["status"]))
        print("")

    print("docs.json : %s" % docs_path)
    print("style.css : %s" % style_status)
    print("")
    print("Preview locally:")
    print("    mint dev          # http://localhost:3000")
    print("")
    return 1 if bad else 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except IntercomError as exc:
        sys.stderr.write("\nERROR: %s\n" % exc)
        sys.exit(2)
    except KeyboardInterrupt:
        sys.stderr.write("\nInterrupted.\n")
        sys.exit(130)
