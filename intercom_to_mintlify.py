        print("=" * 72)
        print("Pages     : %d generated, %d rewritten"
              % (len(rows), sum(1 for r in rows if r["changed"])))
        print("style.css : %s" % style_status)
        if theme_changes:
            print("docs.json :")
            for change in theme_changes:
                print("              - %s" % change)
        print("")
        for r in rows:
            print("%s %s" % ("~~" if r["changed"] else "ok", r["rel"]))
            print("     sections : %s" % (" > ".join(r["audit"]["found"]) or "none recognised"))
            if r["audit"]["missing"]:
                print("     MISSING  : %s  (add by hand; nothing was invented)"
                      % ", ".join(r["audit"]["missing"]))
